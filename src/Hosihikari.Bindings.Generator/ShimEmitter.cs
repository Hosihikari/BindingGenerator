using System.Globalization;
using System.Text;
using Hosihikari.Bindings.Ir;

namespace Hosihikari.Bindings.Generator;

internal static class ShimEmitter
{
    private const string SelfParameter = "hs_self";

    public static void Emit(
        IrManifest manifest,
        IReadOnlyList<IrRecord> records,
        string outputDirectory,
        string manifestHash,
        AbiPlan plan,
        string abiHeader,
        string targetModule = "bedrock_server")
    {
        foreach (var configuration in manifest.Configurations.OrderBy(configuration => configuration.Id, StringComparer.Ordinal))
        {
            if (plan.Functions.Count == 0)
            {
                EmitStub(outputDirectory, configuration.Id, manifestHash);
                continue;
            }

            var declarations = records.OfType<DeclarationRecord>()
                .GroupBy(declaration => declaration.Id, StringComparer.Ordinal)
                .ToDictionary(group => group.Key, group => group.First(), StringComparer.Ordinal);

            foreach (var surface in plan.Functions
                         .Select(function => function.Surface)
                         .Distinct(StringComparer.Ordinal)
                         .OrderBy(surface => surface, StringComparer.Ordinal))
            {
                var functions = plan.FunctionsForSurface(surface)
                    .OrderBy(function => function.Index)
                    .ToList();
                if (functions.Count == 0)
                {
                    continue;
                }

                EmitSurface(
                    outputDirectory,
                    configuration,
                    surface,
                    manifestHash,
                    functions,
                    declarations,
                    records,
                    plan.LinkCarrier,
                    plan.LlAllocator,
                    plan.SymbolDispatch,
                    targetModule,
                    manifest,
                    abiHeader);
            }
        }
    }

    private static void EmitStub(string outputDirectory, string configuration, string manifestHash)
    {
        var directory = Path.Combine(outputDirectory, "shim", configuration);
        Directory.CreateDirectory(directory);

        var header = new List<string>
        {
            "// <auto-generated/>",
            $"// ir-manifest-sha256: {manifestHash}",
            "#pragma once",
            "",
            "#include <cstdint>",
            "",
            "extern \"C\" {",
            "",
            "struct HosihikariBindingTableV1 {",
            "    std::uint32_t version;",
            "    std::uint32_t size;",
            "};",
            "",
            "const HosihikariBindingTableV1* hosihikari_get_binding_table_v1();",
            "",
            "}",
        };

        var source = new List<string>
        {
            "// <auto-generated/>",
            $"// ir-manifest-sha256: {manifestHash}",
            "#include \"binding_table.h\"",
            "",
            "namespace {",
            "",
            "constexpr HosihikariBindingTableV1 kTable{1, sizeof(HosihikariBindingTableV1)};",
            "",
            "}",
            "",
            "extern \"C\" const HosihikariBindingTableV1* hosihikari_get_binding_table_v1()",
            "{",
            "    return &kTable;",
            "}",
        };

        Write(directory, header, source);
    }

    private static void EmitSurface(
        string outputDirectory,
        IrConfiguration configuration,
        string surface,
        string manifestHash,
        IReadOnlyList<AbiFunction> functions,
        IReadOnlyDictionary<string, DeclarationRecord> declarations,
        IReadOnlyList<IrRecord> records,
        bool linkCarrier,
        bool llAllocator,
        bool symbolDispatch,
        string targetModule,
        IrManifest manifest,
        string abiHeader)
    {
        var directory = Path.Combine(outputDirectory, "shim", configuration.Id, surface);
        Directory.CreateDirectory(directory);
        File.Copy(abiHeader, Path.Combine(directory, "hosihikari_abi.h"), true);

        var header = new List<string>
        {
            "// <auto-generated/>",
            $"// ir-manifest-sha256: {manifestHash}",
            "#pragma once",
            "",
            "#include \"hosihikari_abi.h\"",
            "",
            "#include <cstddef>",
            "#include <cstdint>",
            "",
            "extern \"C\" {",
            "",
            "struct HosihikariBindingTableV1 {",
            "    std::uint32_t version;",
            "    std::uint32_t size;",
        };

        foreach (var function in functions)
        {
            header.Add($"    {CppFunctionPointer(function)};");
        }

        header.AddRange(
        [
            "};",
            "",
            "HOSIHIKARI_SHIM_EXPORT const HosihikariBindingTableV1* hosihikari_get_binding_table_v1();",
            "HOSIHIKARI_SHIM_EXPORT const char* hosihikari_get_last_error() noexcept;",
        ]);
        if (string.Equals(surface, "endstone", StringComparison.Ordinal))
        {
            header.Add("HOSIHIKARI_SHIM_EXPORT void* hosihikari_endstone_get_server() noexcept;");
        }

        header.AddRange(
        [
            "",
            "}",
        ]);

        if (symbolDispatch)
        {
            WriteSymbolSurface(
                directory,
                header,
                manifestHash,
                configuration,
                surface,
                functions,
                records,
                targetModule,
                manifest);
            return;
        }

        var source = new List<string>
        {
            "// <auto-generated/>",
            $"// ir-manifest-sha256: {manifestHash}",
            "#include \"binding_table.h\"",
            "",
            "#include <bit>",
            "#include <chrono>",
            "#include <cstddef>",
            "#include <cstdint>",
            "#include <exception>",
            "#include <filesystem>",
            "#include <functional>",
            "#include <memory>",
            "#include <mutex>",
            "#include <new>",
            "#include <optional>",
            "#include <stdexcept>",
            "#include <string>",
            "#include <string_view>",
            "#include <type_traits>",
            "#include <typeindex>",
            "#include <unordered_map>",
            "#include <utility>",
            "#include <variant>",
            "#include <vector>",
        };
        if (llAllocator)
        {
            source.Add("#include \"ll/api/memory/Memory.h\"");
            source.Add("#include \"mc/deps/core/memory/IMemoryAllocator.h\"");
        }

        if (string.Equals(surface, "endstone", StringComparison.Ordinal))
        {
            // The Endstone public API relies on declaration order and complete types; the
            // umbrella keeps the generated translation unit equivalent to a plugin build.
            source.Add("#include \"endstone/endstone.hpp\"");
            source.Add("#include \"endstone/detail.h\"");
        }
        else
        {
            foreach (var include in BuildIncludes(functions, declarations))
            {
                source.Add($"#include \"{include}\"");
            }
        }

        if (llAllocator)
        {
            source.Add("");
            source.Add("void* operator new(std::size_t size)");
            source.Add("{");
            source.Add("    if (void* block = ::ll::memory::getDefaultAllocator()._allocate(size)) { return block; }");
            source.Add("    throw std::bad_alloc();");
            source.Add("}");
            source.Add("void* operator new[](std::size_t size) { return ::operator new(size); }");
            source.Add("void* operator new(std::size_t size, std::nothrow_t const&) noexcept");
            source.Add("{");
            source.Add("    return ::ll::memory::getDefaultAllocator()._allocate(size);");
            source.Add("}");
            source.Add("void* operator new[](std::size_t size, std::nothrow_t const& tag) noexcept");
            source.Add("{");
            source.Add("    return ::operator new(size, tag);");
            source.Add("}");
            source.Add("void* operator new(std::size_t size, std::align_val_t alignment)");
            source.Add("{");
            source.Add("    if (void* block = ::ll::memory::getDefaultAllocator()._alignedAllocate(size, static_cast<std::size_t>(alignment))) { return block; }");
            source.Add("    throw std::bad_alloc();");
            source.Add("}");
            source.Add("void* operator new[](std::size_t size, std::align_val_t alignment) { return ::operator new(size, alignment); }");
            source.Add("void operator delete(void* block) noexcept");
            source.Add("{");
            source.Add("    if (block) { ::ll::memory::getDefaultAllocator()._release(block); }");
            source.Add("}");
            source.Add("void operator delete[](void* block) noexcept { ::operator delete(block); }");
            source.Add("void operator delete(void* block, std::size_t) noexcept { ::operator delete(block); }");
            source.Add("void operator delete[](void* block, std::size_t) noexcept { ::operator delete(block); }");
            source.Add("void operator delete(void* block, std::nothrow_t const&) noexcept { ::operator delete(block); }");
            source.Add("void operator delete[](void* block, std::nothrow_t const&) noexcept { ::operator delete(block); }");
            source.Add("void operator delete(void* block, std::align_val_t alignment) noexcept");
            source.Add("{");
            source.Add("    if (block) { ::ll::memory::getDefaultAllocator()._alignedRelease(block); }");
            source.Add("}");
            source.Add("void operator delete[](void* block, std::align_val_t alignment) noexcept { ::operator delete(block, alignment); }");
            source.Add("void operator delete(void* block, std::size_t, std::align_val_t alignment) noexcept { ::operator delete(block, alignment); }");
            source.Add("void operator delete[](void* block, std::size_t, std::align_val_t alignment) noexcept { ::operator delete(block, alignment); }");
        }

        source.Add("");
        source.Add("namespace {");
        source.Add("");
        source.Add("using hosihikari::abi::setLastError;");
        source.Add("thread_local std::string g_stringResult;");
        source.Add("");
        source.Add("template <class T, class U>");
        source.Add("std::vector<T> hs_make_vector(U const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<T> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.push_back(static_cast<T>(data[i])); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("inline std::vector<std::string> hs_make_string_vector(HosihikariStringView const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<std::string> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.emplace_back(data[i].data, data[i].size); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("struct hs_unique_void_deleter");
        source.Add("{");
        source.Add("    void operator()(void*) const noexcept {}");
        source.Add("};");
        source.Add("struct hs_shared_holder_base");
        source.Add("{");
        source.Add("    virtual ~hs_shared_holder_base() = default;");
        source.Add("    virtual std::shared_ptr<const void> hs_share() const = 0;");
        source.Add("    virtual std::type_index hs_type() const = 0;");
        source.Add("};");
        source.Add("");
        source.Add("template <class T>");
        source.Add("struct hs_shared_holder final : hs_shared_holder_base");
        source.Add("{");
        source.Add("    explicit hs_shared_holder(std::shared_ptr<T> value) : value(std::move(value)) {}");
        source.Add("    std::shared_ptr<T> value;");
        source.Add("    std::shared_ptr<const void> hs_share() const override");
        source.Add("    {");
        source.Add("        return std::shared_ptr<const void>(value, value.get());");
        source.Add("    }");
        source.Add("");
        source.Add("    std::type_index hs_type() const override { return std::type_index(typeid(T)); }");
        source.Add("};");
        source.Add("");
        source.Add("template <class T>");
        source.Add("void hs_release_shared_holder(void* holder)");
        source.Add("{");
        source.Add("    delete static_cast<hs_shared_holder<T>*>(holder);");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("HosihikariSharedHandle hs_make_shared_handle(std::shared_ptr<T> value)");
        source.Add("{");
        source.Add("    if (!value) { return HosihikariSharedHandle{nullptr, nullptr, nullptr}; }");
        source.Add("    auto* holder = new hs_shared_holder<T>(std::move(value));");
        source.Add("    return HosihikariSharedHandle{holder, const_cast<void*>(static_cast<void const*>(holder->value.get())), &hs_release_shared_holder<T>};");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("HosihikariSharedHandle hs_make_non_owner_handle(std::shared_ptr<T> value)");
        source.Add("{");
        source.Add("    if (!value) { return HosihikariSharedHandle{nullptr, nullptr, nullptr}; }");
        source.Add("    void* target = *reinterpret_cast<void**>(value.get());");
        source.Add("    auto* holder = new hs_shared_holder<T>(std::move(value));");
        source.Add("    return HosihikariSharedHandle{holder, target, &hs_release_shared_holder<T>};");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("std::shared_ptr<T> hs_shared_from_handle(HosihikariSharedHandle handle)");
        source.Add("{");
        source.Add("    if (handle.holder == nullptr) { return {}; }");
        source.Add("    auto* holder = static_cast<hs_shared_holder_base*>(handle.holder);");
        source.Add("    if (holder->hs_type() != std::type_index(typeid(T))) {");
        source.Add("        throw std::invalid_argument(\"shared handle type mismatch\");");
        source.Add("    }");
        source.Add("    using Value = std::remove_const_t<T>;");
        source.Add("    auto shared = holder->hs_share();");
        source.Add("    auto* raw = const_cast<Value*>(static_cast<Value const*>(shared.get()));");
        source.Add("    return std::shared_ptr<T>(std::move(shared), raw);");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("std::weak_ptr<T> hs_weak_from_handle(HosihikariSharedHandle handle)");
        source.Add("{");
        source.Add("    return std::weak_ptr<T>(hs_shared_from_handle<T>(handle));");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("struct hs_borrowed_holder");
        source.Add("{");
        source.Add("    std::vector<std::string> strings;");
        source.Add("    std::unique_ptr<T> value;");
        source.Add("};");
        source.Add("");
        source.Add("struct hs_borrowed_entry");
        source.Add("{");
        source.Add("    void* holder;");
        source.Add("    void (*release)(void*);");
        source.Add("};");
        source.Add("");
        source.Add("inline std::mutex hs_borrowedMutex;");
        source.Add("inline std::unordered_map<void*, hs_borrowed_entry> hs_borrowedRegistry;");
        source.Add("");
        source.Add("inline void hs_register_borrowed(void* target, void* holder, void (*release)(void*))");
        source.Add("{");
        source.Add("    std::lock_guard<std::mutex> lock(hs_borrowedMutex);");
        source.Add("    hs_borrowedRegistry[target] = hs_borrowed_entry{holder, release};");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("void hs_destroy_borrowed_or_delete(void* target)");
        source.Add("{");
        source.Add("    void* holder = nullptr;");
        source.Add("    void (*release)(void*) = nullptr;");
        source.Add("    {");
        source.Add("        std::lock_guard<std::mutex> lock(hs_borrowedMutex);");
        source.Add("        auto it = hs_borrowedRegistry.find(target);");
        source.Add("        if (it != hs_borrowedRegistry.end())");
        source.Add("        {");
        source.Add("            holder = it->second.holder;");
        source.Add("            release = it->second.release;");
        source.Add("            hs_borrowedRegistry.erase(it);");
        source.Add("        }");
        source.Add("    }");
        source.Add("");
        source.Add("    if (release) { release(holder); }");
        source.Add("    else { delete static_cast<T*>(target); }");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("std::vector<T> hs_make_record_vector(void const* const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<T> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.push_back(*static_cast<T const*>(data[i])); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("template <class T>");
        source.Add("std::vector<std::optional<T>> hs_make_optional_record_vector(void const* const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<std::optional<T>> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.push_back(data[i] ? std::optional<T>(*static_cast<T const*>(data[i])) : std::nullopt); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("template <class V>");
        source.Add("std::vector<V> hs_make_variant_vector(void const* const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<V> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.push_back(*static_cast<V const*>(data[i])); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("");
        source.Add("inline std::vector<std::basic_string_view<char>> hs_make_string_view_vector(HosihikariStringView const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<std::basic_string_view<char>> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.emplace_back(data[i].data, data[i].size); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("");

        foreach (var function in functions)
        {
            foreach (var line in EmitFunction(function, llAllocator))
            {
                source.Add(line);
            }

            source.Add("");
        }

        source.Add("const HosihikariBindingTableV1 kTable{");
        source.Add("    std::uint32_t{1},");
        source.Add("    static_cast<std::uint32_t>(sizeof(HosihikariBindingTableV1)),");
        foreach (var function in functions)
        {
            source.Add($"    &{function.CppName},");
        }

        source.Add("};");
        source.Add("");
        source.Add("}  // namespace");
        source.Add("");
        source.Add("extern \"C\" HOSIHIKARI_SHIM_EXPORT const HosihikariBindingTableV1* hosihikari_get_binding_table_v1()");
        source.Add("{");
        source.Add("    return &kTable;");
        source.Add("}");
        source.Add("");
        source.Add("extern \"C\" HOSIHIKARI_SHIM_EXPORT const char* hosihikari_get_last_error() noexcept");
        source.Add("{");
        source.Add("    return hosihikari::abi::lastError();");
        source.Add("}");

        if (string.Equals(surface, "endstone", StringComparison.Ordinal))
        {
            source.Add("");
            source.Add("extern \"C\" HOSIHIKARI_SHIM_EXPORT void* hosihikari_endstone_get_server() noexcept");
            source.Add("{");
            source.Add("    try { return &::endstone::detail::getServer(); }");
            source.Add("    catch (std::exception const& hs_error) { setLastError(hs_error.what()); return nullptr; }");
            source.Add("    catch (...) { setLastError(\"unknown native error\"); return nullptr; }");
            source.Add("}");
        }

        // The IR is produced on Windows, where int64_t prints as "long long" and
        // uint64_t as "unsigned long long". Fixed-width aliases keep the generated
        // C++ type identity portable to libstdc++, where int64_t is "long".
        for (var index = 0; index < source.Count; index++)
        {
            source[index] = source[index]
                .Replace("unsigned long long int", "std::uint64_t", StringComparison.Ordinal)
                .Replace("long long int", "std::int64_t", StringComparison.Ordinal)
                .Replace("unsigned long long", "std::uint64_t", StringComparison.Ordinal)
                .Replace("long long", "std::int64_t", StringComparison.Ordinal);
        }

        Write(directory, header, source);
    }

    private static void Write(string directory, List<string> header, List<string> source)
    {
        File.WriteAllText(
            Path.Combine(directory, "binding_table.h"),
            string.Join("\n", header) + "\n",
            new UTF8Encoding(false));
        File.WriteAllText(
            Path.Combine(directory, "binding_table.cpp"),
            string.Join("\n", source) + "\n",
            new UTF8Encoding(false));
    }

    private static IEnumerable<string> BuildIncludes(
        IReadOnlyList<AbiFunction> functions,
        IReadOnlyDictionary<string, DeclarationRecord> declarations)
    {
        var declarationsByQualifiedName = declarations.Values
            .GroupBy(declaration => declaration.QualifiedName, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.First(), StringComparer.Ordinal);
        var includes = new HashSet<string>(StringComparer.Ordinal);

        foreach (var id in functions
                     .Select(function => function.DeclarationId)
                     .Concat(functions
                         .Select(function => function.TargetDeclarationId)
                         .OfType<string>())
                     .Distinct(StringComparer.Ordinal))
        {
            if (!declarations.TryGetValue(id, out var declaration))
            {
                continue;
            }

            if (!string.IsNullOrWhiteSpace(declaration.Source?.File))
            {
                includes.Add(declaration.Source!.File);
            }

            if (declaration.Template is null)
            {
                continue;
            }

            var visited = new HashSet<string>(StringComparer.Ordinal);
            foreach (var argument in declaration.Template.Arguments)
            {
                if (string.Equals(argument.Kind, "pack", StringComparison.Ordinal))
                {
                    foreach (var part in AbiPlan.PackArgumentParts(argument.Value))
                    {
                        CollectTemplateDependencyIncludes(
                            part,
                            declarationsByQualifiedName,
                            includes,
                            visited);
                    }
                }
                else if (string.Equals(argument.Kind, "type", StringComparison.Ordinal))
                {
                    CollectTemplateDependencyIncludes(
                        argument.Value,
                        declarationsByQualifiedName,
                        includes,
                        visited);
                }
            }
        }

        return includes
            .Select(NormalizeInclude)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(file => file, StringComparer.Ordinal);
    }

    private static void CollectTemplateDependencyIncludes(
        string value,
        IReadOnlyDictionary<string, DeclarationRecord> declarationsByQualifiedName,
        HashSet<string> includes,
        HashSet<string> visited)
    {
        var type = AbiPlan.NormalizeTemplateTypeName(value);
        if (string.IsNullOrWhiteSpace(type)
            || AbiPlan.IsFundamentalTemplateArgument(type)
            || AbiPlan.IsLiteralTemplateArgument(type)
            || !visited.Add(type))
        {
            return;
        }

        if (declarationsByQualifiedName.TryGetValue(type, out var declaration))
        {
            if (!string.IsNullOrWhiteSpace(declaration.Source?.File))
            {
                includes.Add(declaration.Source!.File);
            }

            if (declaration.Template is not null)
            {
                foreach (var argument in declaration.Template.Arguments)
                {
                    if (string.Equals(argument.Kind, "pack", StringComparison.Ordinal))
                    {
                        foreach (var part in AbiPlan.PackArgumentParts(argument.Value))
                        {
                            CollectTemplateDependencyIncludes(
                                part,
                                declarationsByQualifiedName,
                                includes,
                                visited);
                        }
                    }
                    else if (string.Equals(argument.Kind, "type", StringComparison.Ordinal))
                    {
                        CollectTemplateDependencyIncludes(
                            argument.Value,
                            declarationsByQualifiedName,
                            includes,
                            visited);
                    }
                }
            }

            return;
        }

        if (!AbiPlan.IsStandardOrThirdPartyType(type))
        {
            return;
        }

        var inner = AbiPlan.ExtractTemplateArguments(type);
        if (inner is null)
        {
            return;
        }

        foreach (var part in AbiPlan.SplitTemplateArguments(inner))
        {
            CollectTemplateDependencyIncludes(part, declarationsByQualifiedName, includes, visited);
        }
    }

    private static string NormalizeInclude(string sourceFile)
    {
        var path = sourceFile.Replace('\\', '/').TrimStart('/');
        if (path.StartsWith("src-server/", StringComparison.Ordinal))
        {
            return path["src-server/".Length..];
        }

        if (path.StartsWith("src/", StringComparison.Ordinal))
        {
            return path["src/".Length..];
        }

        return path;
    }

    private static string CppFunctionPointer(AbiFunction function)
    {
        var returnType = AbiPlan.CppType(function.ReturnKind);
        var parameters = new List<string>();
        if (function.Kind != AbiFunctionKind.Create && !function.Static)
        {
            parameters.Add("void*");
        }

        foreach (var parameter in function.Parameters)
        {
            if (parameter.IsVector || parameter.IsMap)
            {
                continue;
            }

            switch (parameter.Kind)
            {
                case AbiKind.StringView:
                    parameters.Add("const char*");
                    parameters.Add("std::size_t");
                    break;
                case AbiKind.Opaque:
                    parameters.Add("void*");
                    break;
                case AbiKind.Callback:
                    parameters.Add("void*");
                    parameters.Add("void*");
                    parameters.Add("void*");
                    break;
                default:
                    parameters.Add(AbiPlan.CppType(parameter.Kind));
                    break;
            }
        }

        foreach (var parameter in function.Parameters.Where(parameter => parameter.IsVector))
        {
            if (parameter.VectorElementKind == AbiKind.Opaque
                && parameter.VectorElementOwnership != ArrayElementOwnership.PairCopy)
            {
                // Handles are pointers to mutable objects; the array itself is read-only.
                parameters.Add("void* const*");
            }
            else
            {
                parameters.Add("const " + (parameter.VectorElementOwnership == ArrayElementOwnership.PairCopy
                    ? "HosihikariMapEntry"
                    : parameter.VectorElementKind == AbiKind.StringView
                        ? "HosihikariStringView"
                        : AbiPlan.CppType(parameter.VectorElementKind)) + "*");
            }

            parameters.Add("std::size_t");
        }

        foreach (var _ in function.Parameters.Where(parameter => parameter.IsMap))
        {
            parameters.Add("HosihikariArrayView");
        }

        foreach (var parameter in function.Parameters.Where(parameter => parameter.IsOptional))
        {
            parameters.Add("bool");
        }

        if (function.NeedsPresenceFlag)
        {
            parameters.Add("bool*");
        }

        var parameterList = parameters.Count == 0 ? "void" : string.Join(", ", parameters);
        return $"{returnType} (*{function.TableField})({parameterList})";
    }

    private static IEnumerable<string> EmitFunction(AbiFunction function, bool llAllocator)
    {
        var returnType = AbiPlan.CppType(function.ReturnKind);
        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var callbackParameter = function.Parameters[index];
            if (callbackParameter.Kind != AbiKind.Callback)
            {
                continue;
            }

            foreach (var line in EmitCallbackSupport(function, index, callbackParameter))
            {
                yield return line;
            }

            yield return "";
        }

        var parameters = new List<string>();
        if (function.Kind != AbiFunctionKind.Create && !function.Static)
        {
            parameters.Add($"void* {SelfParameter}");
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.IsVector || parameter.IsMap)
            {
                continue;
            }

            var name = function.Kind == AbiFunctionKind.Set
                ? "value"
                : CppParameterName(parameter, index);
            switch (parameter.Kind)
            {
                case AbiKind.StringView:
                    parameters.Add($"const char* {name}_data");
                    parameters.Add($"std::size_t {name}_size");
                    break;
                case AbiKind.Opaque:
                    parameters.Add($"void* {name}");
                    break;
                case AbiKind.Callback:
                    parameters.Add($"void* {name}_invoke");
                    parameters.Add($"void* {name}_userData");
                    parameters.Add($"void* {name}_release");
                    break;
                default:
                    parameters.Add($"{AbiPlan.CppType(parameter.Kind)} {name}");
                    break;
            }
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.IsVector)
            {
                var name = CppParameterName(parameter, index);
                if (parameter.VectorElementKind == AbiKind.Opaque
                    && parameter.VectorElementOwnership != ArrayElementOwnership.PairCopy)
                {
                    parameters.Add($"void* const* {name}_data");
                }
                else
                {
                    var elementType = parameter.VectorElementOwnership == ArrayElementOwnership.PairCopy
                        ? "HosihikariMapEntry"
                        : parameter.VectorElementKind == AbiKind.StringView
                            ? "HosihikariStringView"
                            : AbiPlan.CppType(parameter.VectorElementKind);
                    parameters.Add($"const {elementType}* {name}_data");
                }

                parameters.Add($"std::size_t {name}_count");
            }
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.IsMap)
            {
                parameters.Add($"HosihikariArrayView {CppParameterName(parameter, index)}_map");
            }
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.IsOptional)
            {
                parameters.Add($"bool {CppParameterName(parameter, index)}_hasValue");
            }
        }

        if (function.NeedsPresenceFlag)
        {
            parameters.Add("bool* hs_hasValue");
        }

        yield return $"static {returnType} {function.CppName}({string.Join(", ", parameters)}) try";
        yield return "{";

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (!parameter.IsMap)
            {
                continue;
            }

            foreach (var line in EmitMapParameterConstruction(parameter, index))
            {
                yield return "    " + line;
            }
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (!parameter.IsVector || parameter.VectorElementOwnership != ArrayElementOwnership.PairCopy)
            {
                continue;
            }

            foreach (var line in EmitPairVectorConstruction(parameter, index))
            {
                yield return "    " + line;
            }
        }

        switch (function.Kind)
        {
            case AbiFunctionKind.Create:
                if (function.VariantOp == VariantOp.Create)
                {
                    foreach (var line in EmitVariantCreate(function))
                    {
                        yield return line;
                    }

                    break;
                }

                if (function.CreateViaBorrowedHolder)
                {
                    foreach (var line in EmitBorrowedCreate(function))
                    {
                        yield return line;
                    }

                    break;
                }

                yield return $"    return new {function.ClassCppName}({string.Join(", ", BuildNativeArguments(function))});";
                break;

            case AbiFunctionKind.Destroy:
                yield return function.DestroyViaBorrowedHolder
                    ? $"    hs_destroy_borrowed_or_delete<{function.ClassCppName}>({SelfParameter});"
                    : $"    delete static_cast<{function.ClassCppName}*>({SelfParameter});";
                break;

            case AbiFunctionKind.Get:
            {
                var target = FieldTarget(function);
                if (function.ReturnKind == AbiKind.StringView)
                {
                    yield return $"    auto const& value = {target};";
                    yield return "    return HosihikariStringView{value.data(), value.size()};";
                }
                else if (function.ReturnKind == AbiKind.Shared)
                {
                    var sharedExpression = function.SharedWrapper is SharedWrapperKind.NotNull or SharedWrapperKind.Nullable
                        ? $"({target}).get()"
                        : target;
                    yield return $"    return hs_make_shared_handle({sharedExpression});";
                }
                else if (function.ReturnKind == AbiKind.Opaque)
                {
                    // A pointer field is returned as-is; references, arrays, and by-value
                    // records are exposed through the address of the field.
                    var address = AbiPlan.IsPointerType(function.NativeReturnType)
                        ? target
                        : "&" + target;
                    yield return $"    return const_cast<void*>(static_cast<void const*>({address}));";
                }
                else
                {
                    yield return $"    return static_cast<{returnType}>({target});";
                }

                break;
            }

            case AbiFunctionKind.Set:
            {
                var target = FieldTarget(function);
                var value = function.Parameters.Count == 0
                    ? "value"
                    : NativeArgument(function, function.Parameters[0], 0, "value");
                yield return $"    {target} = static_cast<{function.Parameters[0].NativeType}>({value});";
                break;
            }

            case AbiFunctionKind.Cast:
                yield return function.CastKind == AbiCastKind.Downcast
                    ? $"    return dynamic_cast<{function.TargetCppName}*>(static_cast<{function.ClassCppName}*>({SelfParameter}));"
                    : $"    return static_cast<{function.TargetCppName}*>(static_cast<{function.ClassCppName}*>({SelfParameter}));";
                break;

            case AbiFunctionKind.DirectorCreate:
                foreach (var line in EmitDirectorCreate(function))
                {
                    yield return line;
                }

                break;

            case AbiFunctionKind.FreeFunction:
            {
                var call = $"{function.NativeMemberName}({string.Join(", ", BuildNativeArguments(function))})";
                if (function.ReturnKind == AbiKind.Void)
                {
                    yield return $"    {call};";
                }
                else if (function.ReturnKind == AbiKind.StringView)
                {
                    yield return $"    auto result = {call};";
                    yield return "    g_stringResult.assign(result.data(), result.size());";
                    yield return "    return HosihikariStringView{g_stringResult.data(), g_stringResult.size()};";
                }
                else if (function.ReturnKind == AbiKind.Opaque)
                {
                    var address = function.NativeReturnType.TrimEnd().EndsWith("&", StringComparison.Ordinal)
                        ? "&" + call
                        : call;
                    yield return $"    return const_cast<void*>(static_cast<void const*>({address}));";
                }
                else
                {
                    yield return $"    return static_cast<{AbiPlan.CppType(function.ReturnKind)}>({call});";
                }

                break;
            }

            case AbiFunctionKind.Method:
            {
                if (function.CallableOp == CallableOp.Invoke)
                {
                    var arguments = string.Join(", ", BuildNativeArguments(function));
                    var invocation = $"(*static_cast<{function.ClassCppName}*>({SelfParameter}))({arguments})";
                    if (function.ReturnKind == AbiKind.Void)
                    {
                        yield return $"    {invocation};";
                    }
                    else
                    {
                        yield return $"    return static_cast<{AbiPlan.CppType(function.ReturnKind)}>({invocation});";
                    }

                    break;
                }

                if (function.VariantOp is VariantOp.Index or VariantOp.Get)
                {
                    foreach (var line in EmitVariantRead(function))
                    {
                        yield return line;
                    }

                    break;
                }

                var memberName = function.NativeMemberName;
                if (memberName.StartsWith("operator ", StringComparison.Ordinal)
                    && function.ReturnKind != AbiKind.Void
                    && !memberName["operator ".Length..].Contains("::", StringComparison.Ordinal)
                    && function.NativeReturnType.Contains("::", StringComparison.Ordinal))
                {
                    var targetType = function.NativeReturnType.TrimEnd();
                    while (targetType.EndsWith("&", StringComparison.Ordinal)
                        || targetType.EndsWith("*", StringComparison.Ordinal))
                    {
                        targetType = targetType[..^1].TrimEnd();
                    }

                    memberName = "operator " + targetType;
                }

                var target = function.Static
                    ? $"{function.ClassCppName}::{memberName}"
                    : $"static_cast<{function.ClassCppName}*>({SelfParameter})->{memberName}";
                var call = $"{target}({string.Join(", ", BuildNativeArguments(function))})";
                var expectedVoid = function.ReturnExpected && function.ReturnKind == AbiKind.Void;
                if (function.ReturnExpected)
                {
                    yield return $"    auto hs_expected = {call};";
                    yield return "    if (!hs_expected)";
                    yield return "    {";
                    yield return $"        setLastError({ExpectedErrorText(function)});";
                    yield return "        *hs_hasValue = false;";
                    yield return $"        {DefaultReturn(function.ReturnKind)}";
                    yield return "    }";
                    yield return "    *hs_hasValue = true;";
                    if (!expectedVoid)
                    {
                        call = "std::move(*hs_expected)";
                    }
                }

                if (function.ReturnKind == AbiKind.Void)
                {
                    if (!expectedVoid)
                    {
                        yield return $"    {call};";
                    }
                }
                else if (function.ReturnKind == AbiKind.StringView)
                {
                    yield return $"    auto result = {call};";
                    if (function.SpecialValue == SpecialValueKind.Path)
                    {
                        if (function.ReturnOptional)
                        {
                            yield return "    *hs_hasValue = result.has_value();";
                            yield return "    g_stringResult.assign(result ? result->string() : \"\");";
                        }
                        else
                        {
                            yield return "    g_stringResult.assign(result.string());";
                        }

                        yield return "    return HosihikariStringView{g_stringResult.data(), g_stringResult.size()};";
                    }
                    else if (function.ReturnOptional)
                    {
                        yield return "    *hs_hasValue = result.has_value();";
                        yield return "    g_stringResult.assign(result ? result->data() : \"\", result ? result->size() : 0);";
                    }
                    else
                    {
                        yield return "    g_stringResult.assign(result.data(), result.size());";
                    }

                    if (function.SpecialValue != SpecialValueKind.Path)
                    {
                        yield return "    return HosihikariStringView{g_stringResult.data(), g_stringResult.size()};";
                    }
                }
                else if (function.ReturnKind == AbiKind.MapView)
                {
                    yield return "    thread_local std::vector<HosihikariMapEntry> hs_mapEntries;";
                    yield return "    thread_local std::vector<std::string> hs_mapStrings;";
                    yield return $"    auto result = {call};";
                    yield return "    hs_mapEntries.clear();";
                    yield return "    hs_mapEntries.reserve(result.size());";
                    yield return "    hs_mapStrings.clear();";
                    yield return "    hs_mapStrings.reserve(result.size() * 2);";
                    yield return "    for (auto const& item : result)";
                    yield return "    {";
                    yield return "        HosihikariMapEntry entry{};";
                    foreach (var line in EmitMapEncode(
                        function.MapKeyKind,
                        ArrayElementOwnership.None,
                        null,
                        "entry.key",
                        "entry.keySize",
                        "item.first"))
                    {
                        yield return "        " + line;
                    }

                    foreach (var line in EmitMapEncode(
                        function.MapValueKind,
                        function.MapValueOwnership,
                        function.MapValueNativeType,
                        "entry.value",
                        "entry.valueSize",
                        "item.second"))
                    {
                        yield return "        " + line;
                    }

                    yield return "        hs_mapEntries.push_back(entry);";
                    yield return "    }";
                    yield return "    return HosihikariArrayView{hs_mapEntries.data(), hs_mapEntries.size()};";
                }
                else if (function.ReturnKind == AbiKind.ArrayView)
                {
                    if (function.ArrayElementKind == AbiKind.StringView)
                    {
                        yield return "    thread_local std::vector<std::string> hs_arrayStrings;";
                        yield return "    thread_local std::vector<HosihikariStringView> hs_arrayViews;";
                        yield return $"    auto result = {call};";
                        yield return "    hs_arrayStrings.clear();";
                        yield return "    hs_arrayViews.clear();";
                        yield return "    hs_arrayStrings.reserve(result.size());";
                        yield return "    for (auto const& item : result) { hs_arrayStrings.emplace_back(item.data(), item.size()); }";
                        yield return "    hs_arrayViews.reserve(hs_arrayStrings.size());";
                        yield return "    for (auto const& item : hs_arrayStrings) { hs_arrayViews.push_back(HosihikariStringView{item.data(), item.size()}); }";
                        yield return "    return HosihikariArrayView{hs_arrayViews.data(), hs_arrayViews.size()};";
                    }
                    else if (function.ArrayElementKind == AbiKind.Shared)
                    {
                        yield return "    thread_local std::vector<HosihikariSharedHandle> hs_arrayShared;";
                        yield return $"    auto result = {call};";
                        yield return "    hs_arrayShared.clear();";
                        yield return "    hs_arrayShared.reserve(result.size());";
                        var sharedExpression = function.ArrayElementSharedWrapper is SharedWrapperKind.NotNull or SharedWrapperKind.Nullable
                            ? "item.get()"
                            : "item";
                        yield return $"    for (auto const& item : result) {{ hs_arrayShared.push_back(hs_make_shared_handle({sharedExpression})); }}";
                        yield return "    return HosihikariArrayView{hs_arrayShared.data(), hs_arrayShared.size()};";
                    }
                    else
                    {
                        var elementType = AbiPlan.CppType(function.ArrayElementKind);
                        yield return $"    thread_local std::vector<{elementType}> hs_arrayResult;";
                        yield return $"    auto result = {call};";
                        yield return "    hs_arrayResult.clear();";
                        yield return "    hs_arrayResult.reserve(result.size());";
                        if (function.ArrayElementKind == AbiKind.Opaque
                            && function.ArrayElementOwnership == ArrayElementOwnership.None)
                        {
                            yield return "    for (auto const& item : result) { hs_arrayResult.push_back(const_cast<void*>(static_cast<void const*>(item))); }";
                        }
                        else if (function.ArrayElementOwnership == ArrayElementOwnership.UniquePtr)
                        {
                            yield return "    for (auto& item : result) { hs_arrayResult.push_back(static_cast<void*>(item.release())); }";
                        }
                        else if (function.ArrayElementOwnership == ArrayElementOwnership.RecordCopy)
                        {
                            var recordType = function.ArrayElementNativeType ?? "void";
                            yield return $"    for (auto const& item : result) {{ hs_arrayResult.push_back(static_cast<void*>(new {recordType}(item))); }}";
                        }
                        else if (function.ArrayElementOwnership == ArrayElementOwnership.OptionalRecordCopy)
                        {
                            var recordType = function.ArrayElementNativeType ?? "void";
                            yield return $"    for (auto const& item : result) {{ hs_arrayResult.push_back(item ? static_cast<void*>(new {recordType}(*item)) : nullptr); }}";
                        }
                        else if (function.ArrayElementOwnership == ArrayElementOwnership.VariantCopy)
                        {
                            var variantType = function.ArrayElementNativeType ?? "void";
                            yield return $"    for (auto const& item : result) {{ hs_arrayResult.push_back(static_cast<void*>(new {variantType}(item))); }}";
                        }
                        else
                        {
                            yield return $"    for (auto const& item : result) {{ hs_arrayResult.push_back(static_cast<{elementType}>(item)); }}";
                        }

                        yield return "    return HosihikariArrayView{hs_arrayResult.data(), hs_arrayResult.size()};";
                    }
                }
                else if (function.ReturnKind == AbiKind.Shared)
                {
                    var sharedExpression = function.SharedWrapper is SharedWrapperKind.NotNull or SharedWrapperKind.Nullable
                        ? $"({call}).get()"
                        : call;
                    yield return $"    return hs_make_shared_handle({sharedExpression});";
                }
                else if (function.SpecialValue is SpecialValueKind.TypeId or SpecialValueKind.StrongOrdering)
                {
                    var fallback = AbiPlan.CppType(function.ReturnKind) + "{0}";
                    if (function.ReturnOptional)
                    {
                        yield return $"    auto result = {call};";
                        yield return "    *hs_hasValue = result.has_value();";
                        yield return $"    return result ? {SpecialReturnExpression(function, "*result")} : {fallback};";
                    }
                    else
                    {
                        yield return $"    return {SpecialReturnExpression(function, call)};";
                    }
                }
                else if (function.TimeConversion != TimeConversion.None)
                {
                    if (function.ReturnOptional)
                    {
                        yield return $"    auto result = {call};";
                        yield return "    *hs_hasValue = result.has_value();";
                        yield return $"    return result ? {TimeReturnExpression(function, "*result")} : std::int64_t{{0}};";
                    }
                    else
                    {
                        yield return $"    return {TimeReturnExpression(function, call)};";
                    }
                }
                else if (function.ReturnKind == AbiKind.Opaque)
                {
                    if (function.ReturnOptional && function.ReturnOwned)
                    {
                        yield return $"    auto result = {call};";
                        yield return "    *hs_hasValue = result.has_value();";
                        yield return "    if (!result) { return nullptr; }";
                        yield return $"    return static_cast<void*>(new {function.NativeReturnType}(std::move(*result)));";
                    }
                    else if (function.ReturnOptional)
                    {
                        // A returned optional_ref borrows an existing object; the presence flag
                        // distinguishes an empty reference from a null pointer value.
                        yield return $"    auto result = {call};";
                        yield return "    *hs_hasValue = static_cast<bool>(result);";
                        yield return "    return result ? const_cast<void*>(static_cast<void const*>(&*result)) : nullptr;";
                    }
                    else if (function.ReturnUniquePtr)
                    {
                        yield return $"    auto hs_result = {call};";
                        yield return "    return static_cast<void*>(hs_result.release());";
                    }
                    else if (function.ReturnOwned)
                    {
                        yield return $"    return static_cast<void*>(new {function.NativeReturnType}({call}));";
                    }
                    else
                    {
                        var address = function.NativeReturnType.TrimEnd().EndsWith("&", StringComparison.Ordinal)
                            ? "&" + call
                            : call;
                        yield return $"    return const_cast<void*>(static_cast<void const*>({address}));";
                    }
                }
                else if (function.ReturnOptional)
                {
                    yield return $"    auto result = {call};";
                    yield return "    *hs_hasValue = result.has_value();";
                    yield return $"    return result ? static_cast<{returnType}>(*result) : {returnType}{{}};";
                }
                else
                {
                    yield return $"    return static_cast<{returnType}>({call});";
                }

                break;
            }
        }

        yield return "}";
        yield return "catch (std::exception const& hs_error)";
        yield return "{";
        yield return "    setLastError(hs_error.what());";
        if (function.NeedsPresenceFlag)
        {
            yield return "    if (hs_hasValue) { *hs_hasValue = false; }";
        }

        yield return "    " + DefaultReturn(function.ReturnKind);
        yield return "}";
        yield return "catch (...)";
        yield return "{";
        yield return "    setLastError(\"unknown native exception\");";
        if (function.NeedsPresenceFlag)
        {
            yield return "    if (hs_hasValue) { *hs_hasValue = false; }";
        }

        yield return "    " + DefaultReturn(function.ReturnKind);
        yield return "}";
    }

    private static IEnumerable<string> EmitVariantCreate(AbiFunction function)
    {
        var info = function.VariantInfo!;
        var alternative = function.VariantAlternative!;
        var native = info.NativeType;
        var construct = alternative.Kind switch
        {
            VariantAlternativeKind.String =>
                $"std::in_place_index<{alternative.Index}>, std::string(value_data, value_size)",
            VariantAlternativeKind.Record =>
                $"std::in_place_index<{alternative.Index}>, *static_cast<const {alternative.NativeType}*>(value)",
            _ => $"std::in_place_index<{alternative.Index}>, static_cast<{alternative.NativeType}>(value)",
        };
        yield return $"    return static_cast<void*>(new {native}({construct}));";
    }

    private static IEnumerable<string> EmitBorrowedCreate(AbiFunction function)
    {
        const string holder = "hs_borrowed";
        yield return $"    auto* {holder} = new hs_borrowed_holder<{function.ClassCppName}>();";
        var callArguments = new List<string>();
        var stringOrdinal = 0;
        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.Kind == AbiKind.StringView)
            {
                var name = CppParameterName(parameter, index);
                yield return $"    {holder}->strings.emplace_back({name}_data, {name}_size);";
                callArguments.Add(BorrowedStringCallExpression(parameter, holder, stringOrdinal));
                stringOrdinal++;
            }
            else
            {
                callArguments.Add(NativeArgument(function, parameter, index));
            }
        }

        yield return $"    {holder}->value = std::make_unique<{function.ClassCppName}>({string.Join(", ", callArguments)});";
        yield return $"    auto* hs_target = {holder}->value.get();";
        yield return $"    hs_register_borrowed(hs_target, {holder}, [](void* hs_holder) {{ delete static_cast<hs_borrowed_holder<{function.ClassCppName}>*>(hs_holder); }});";
        yield return "    return hs_target;";
    }

    private static IEnumerable<string> EmitDirectorCreate(AbiFunction function)
    {
        var constructorCount = function.DirectorConstructorParameterCount;
        var names = function.Parameters
            .Select((parameter, index) => CppParameterName(parameter, index))
            .ToList();
        var parameterDeclarations = function.Parameters
            .Select((parameter, index) => $"{AbiPlan.CppType(parameter.Kind)} {names[index]}")
            .ToList();
        var baseArguments = function.Parameters
            .Take(constructorCount)
            .Select((parameter, index) => NativeArgument(function, parameter, index, names[index]))
            .ToList();
        var callbackTypes = function.DirectorCallbackParameters
            .Select(DirectorCallbackCppType)
            .ToList();
        var invokeReturnType = AbiPlan.CppType(function.DirectorReturnKind);
        var invokeType = $"{invokeReturnType} (*)(void*{string.Concat(callbackTypes.Select(type => ", " + type))})";
        var callbackDeclarations = function.DirectorCallbackParameters
            .Select((parameter, index) => $"{parameter.NativeType} hs_arg{index}")
            .ToList();
        var callbackArguments = function.DirectorCallbackParameters
            .Select(DirectorCallbackArgument)
            .ToList();
        var invocation = $"hs_invoke(hs_userData{string.Concat(callbackArguments.Select(argument => ", " + argument))})";
        var methodConst = function.DirectorMethodIsConst ? " const" : "";

        yield return $"    struct hs_director final : {function.ClassCppName}";
        yield return "    {";
        yield return $"        using hs_invoke_type = {invokeType};";
        yield return "        void* hs_userData;";
        yield return "        hs_invoke_type hs_invoke;";
        yield return "        void (*hs_release)(void*);";
        yield return "";
        yield return $"        hs_director({string.Join(", ", parameterDeclarations)})";
        var initializers = new List<string>();
        if (baseArguments.Count > 0)
        {
            initializers.Add($"{function.ClassCppName}({string.Join(", ", baseArguments)})");
        }

        initializers.Add($"hs_invoke(reinterpret_cast<hs_invoke_type>({names[constructorCount]}))");
        initializers.Add($"hs_userData({names[constructorCount + 1]})");
        initializers.Add($"hs_release(reinterpret_cast<void (*)(void*)>({names[constructorCount + 2]}))");
        yield return "            : " + string.Join(", ", initializers);
        yield return "        {";
        yield return "        }";
        yield return "";
        yield return "        ~hs_director() override";
        yield return "        {";
        yield return "            if (hs_release) { hs_release(hs_userData); }";
        yield return "        }";
        yield return "";
        yield return $"        {function.DirectorReturnNativeType} {function.NativeMemberName}({string.Join(", ", callbackDeclarations)}){methodConst} override";
        yield return "        {";
        if (function.DirectorReturnKind == AbiKind.Void)
        {
            yield return $"            if (hs_invoke) {{ {invocation}; }}";
        }
        else
        {
            yield return "            if (!hs_invoke) { return {}; }";
            yield return $"            return static_cast<{function.DirectorReturnNativeType}>({invocation});";
        }

        yield return "        }";
        yield return "    };";
        yield return $"    return hs_make_shared_handle(std::static_pointer_cast<{function.ClassCppName}>(std::make_shared<hs_director>({string.Join(", ", names)})));";
    }

    private static string DirectorCallbackCppType(AbiParameter parameter) =>
        parameter.Kind == AbiKind.Opaque ? "void*" : AbiPlan.CppType(parameter.Kind);

    private static string DirectorCallbackArgument(AbiParameter parameter, int index)
    {
        var name = $"hs_arg{index}";
        if (parameter.Kind == AbiKind.Opaque)
        {
            return parameter.IsReference
                ? $"const_cast<void*>(static_cast<void const*>(&{name}))"
                : $"const_cast<void*>(static_cast<void const*>({name}))";
        }

        return $"static_cast<{AbiPlan.CppType(parameter.Kind)}>({name})";
    }

    private static string BorrowedStringCallExpression(AbiParameter parameter, string holder, int ordinal)
    {
        if (AbiPlan.IsStringViewType(parameter.NativeType))
        {
            return $"std::string_view({holder}->strings[{ordinal}])";
        }

        if (AbiPlan.IsPointerType(parameter.NativeType)
            || parameter.NativeType.Contains("char*", StringComparison.Ordinal))
        {
            return $"{holder}->strings[{ordinal}].c_str()";
        }

        return $"{holder}->strings[{ordinal}]";
    }

    private static IEnumerable<string> EmitVariantRead(AbiFunction function)
    {
        var info = function.VariantInfo!;
        var native = info.NativeType;
        if (function.VariantOp == VariantOp.Index)
        {
            yield return $"    return static_cast<std::int32_t>(static_cast<const {native}*>({SelfParameter})->index());";
            yield break;
        }

        var alternative = function.VariantAlternative!;
        yield return $"    auto const& hs_value = *static_cast<const {native}*>({SelfParameter});";
        if (alternative.Kind == VariantAlternativeKind.String)
        {
            yield return "    thread_local std::string hs_variantString;";
            yield return $"    if (hs_value.index() != {alternative.Index}) {{ return HosihikariStringView{{nullptr, 0}}; }}";
            yield return $"    auto const& hs_text = std::get<{alternative.Index}>(hs_value);";
            yield return "    hs_variantString.assign(hs_text.data(), hs_text.size());";
            yield return "    return HosihikariStringView{hs_variantString.data(), hs_variantString.size()};";
            yield break;
        }

        yield return $"    if (hs_value.index() != {alternative.Index}) {{ {DefaultReturn(function.ReturnKind)} }}";
        if (alternative.Kind == VariantAlternativeKind.Record)
        {
            yield return $"    return static_cast<void*>(new {alternative.NativeType}(std::get<{alternative.Index}>(hs_value)));";
        }
        else if (alternative.Kind == VariantAlternativeKind.Pointer)
        {
            yield return $"    return const_cast<void*>(static_cast<void const*>(std::get<{alternative.Index}>(hs_value)));";
        }
        else
        {
            yield return $"    return static_cast<{AbiPlan.CppType(function.ReturnKind)}>(std::get<{alternative.Index}>(hs_value));";
        }
    }

    private static bool IsSignedScalar(AbiKind kind) =>
        kind is AbiKind.I8 or AbiKind.I16 or AbiKind.I32 or AbiKind.I64 or AbiKind.ISize;

    private static IEnumerable<string> EmitMapEncode(
        AbiKind kind,
        ArrayElementOwnership ownership,
        string? nativeType,
        string target,
        string sizeTarget,
        string expression)
    {
        if (kind == AbiKind.StringView)
        {
            yield return $"hs_mapStrings.emplace_back({expression}.data(), {expression}.size());";
            yield return "auto const& hs_stored = hs_mapStrings.back();";
            yield return $"{target} = reinterpret_cast<std::uint64_t>(hs_stored.data());";
            yield return $"{sizeTarget} = static_cast<std::uint64_t>(hs_stored.size());";
            yield break;
        }

        if (kind == AbiKind.Opaque && ownership != ArrayElementOwnership.None)
        {
            yield return $"{target} = reinterpret_cast<std::uint64_t>(static_cast<void*>(new {nativeType}({expression})));";
            yield break;
        }

        if (kind == AbiKind.Opaque)
        {
            yield return $"{target} = reinterpret_cast<std::uint64_t>(const_cast<void*>(static_cast<void const*>({expression})));";
            yield break;
        }

        yield return IsSignedScalar(kind)
            ? $"{target} = static_cast<std::uint64_t>(static_cast<std::int64_t>({expression}));"
            : $"{target} = static_cast<std::uint64_t>({expression});";
    }

    private static IEnumerable<string> EmitMapParameterConstruction(AbiParameter parameter, int index)
    {
        var name = CppParameterName(parameter, index);
        yield return $"{parameter.NativeType} hs_map{index};";
        yield return $"hs_map{index}.reserve({name}_map.size);";
        yield return $"auto const* hs_map{index}Items = static_cast<HosihikariMapEntry const*>({name}_map.data);";
        yield return $"for (std::size_t hs_map{index}Index = 0; hs_map{index}Index < {name}_map.size; ++hs_map{index}Index)";
        yield return "{";
        yield return $"    auto const& hs_entry = hs_map{index}Items[hs_map{index}Index];";
        yield return $"    hs_map{index}.emplace(";
        yield return $"        {MapEntryDecodeExpression(parameter.MapKeyKind, ArrayElementOwnership.None, parameter.MapKeyNativeType, "key", "keySize")},";
        yield return $"        {MapEntryDecodeExpression(parameter.MapValueKind, parameter.MapValueOwnership, parameter.MapValueNativeType, "value", "valueSize")});";
        yield return "}";
    }

    private static IEnumerable<string> EmitPairVectorConstruction(AbiParameter parameter, int index)
    {
        var name = CppParameterName(parameter, index);
        var pairType = $"std::pair<{parameter.VectorPairKeyType}, {parameter.VectorPairValueType}>";
        yield return $"std::vector<{pairType}> hs_vec{index};";
        yield return $"hs_vec{index}.reserve({name}_count);";
        yield return $"for (std::size_t hs_vec{index}Index = 0; hs_vec{index}Index < {name}_count; ++hs_vec{index}Index)";
        yield return "{";
        yield return $"    auto const& hs_entry = {name}_data[hs_vec{index}Index];";
        yield return $"    hs_vec{index}.emplace_back(";
        yield return $"        {MapEntryDecodeExpression(parameter.VectorPairKeyKind, ArrayElementOwnership.None, parameter.VectorPairKeyType, "key", "keySize")},";
        yield return $"        {MapEntryDecodeExpression(parameter.VectorPairValueKind, ArrayElementOwnership.None, parameter.VectorPairValueType, "value", "valueSize")});";
        yield return "}";
    }

    private static string MapEntryDecodeExpression(
        AbiKind kind,
        ArrayElementOwnership ownership,
        string? nativeType,
        string field,
        string sizeField)
    {
        nativeType ??= "";
        if (kind == AbiKind.StringView)
        {
            var stringType = AbiPlan.IsStringViewType(nativeType) ? "std::string_view" : "std::string";
            return $"{stringType}(reinterpret_cast<char const*>(hs_entry.{field}), hs_entry.{sizeField})";
        }

        if (kind == AbiKind.Opaque)
        {
            return ownership == ArrayElementOwnership.None
                ? $"reinterpret_cast<{nativeType}>(hs_entry.{field})"
                : $"*static_cast<{nativeType} const*>(reinterpret_cast<void const*>(hs_entry.{field}))";
        }

        if (kind == AbiKind.Bool)
        {
            return $"hs_entry.{field} != 0";
        }

        if (kind == AbiKind.F32)
        {
            return $"std::bit_cast<float>(static_cast<std::uint32_t>(hs_entry.{field}))";
        }

        if (kind == AbiKind.F64)
        {
            return $"std::bit_cast<double>(hs_entry.{field})";
        }

        var type = nativeType.Length > 0 ? nativeType : AbiPlan.CppType(kind);
        return IsSignedScalar(kind)
            ? $"static_cast<{type}>(static_cast<std::int64_t>(hs_entry.{field}))"
            : $"static_cast<{type}>(hs_entry.{field})";
    }

    private static string SpecialParameterExpression(AbiParameter parameter, string name) =>
        parameter.SpecialValue switch
        {
            SpecialValueKind.TypeId =>
                $"Bedrock::typeid_t<{parameter.SpecialValueType}>({name})",
            SpecialValueKind.StrongOrdering =>
                $"({name} < 0 ? std::strong_ordering::less : ({name} > 0 ? std::strong_ordering::greater : std::strong_ordering::equal))",
            SpecialValueKind.Path =>
                $"std::filesystem::path(std::string({name}_data, {name}_size))",
            _ => name,
        };

    private static string SpecialReturnExpression(AbiFunction function, string expression) =>
        function.SpecialValue switch
        {
            SpecialValueKind.TypeId =>
                $"static_cast<std::uint16_t>(({expression}).value)",
            SpecialValueKind.StrongOrdering =>
                $"static_cast<std::int8_t>(({expression}) < 0 ? -1 : (({expression}) > 0 ? 1 : 0))",
            _ => expression,
        };

    private static string TimeParameterExpression(AbiParameter parameter, string name) =>
        parameter.TimeConversion switch
        {
            TimeConversion.SystemTimePoint =>
                $"std::chrono::system_clock::time_point(std::chrono::milliseconds({name}))",
            TimeConversion.ClockTimePoint =>
                $"std::chrono::time_point<{parameter.TimeClockType}>({parameter.TimeClockType}::duration({name}))",
            TimeConversion.Duration =>
                $"{parameter.TimeDurationType}({name})",
            _ => name,
        };

    private static string TimeReturnExpression(AbiFunction function, string expression) =>
        function.TimeConversion switch
        {
            TimeConversion.SystemTimePoint =>
                $"static_cast<std::int64_t>(std::chrono::duration_cast<std::chrono::milliseconds>(({expression}).time_since_epoch()).count())",
            TimeConversion.ClockTimePoint =>
                $"static_cast<std::int64_t>(({expression}).time_since_epoch().count())",
            TimeConversion.Duration =>
                $"static_cast<std::int64_t>(({expression}).count())",
            _ => expression,
        };

    private static string ExpectedErrorText(AbiFunction function) =>
        AbiPlan.IsStringType(function.ExpectedErrorType ?? "")
            ? "hs_expected.error().c_str()"
            : "hs_expected.error().message().c_str()";

    private static string DefaultReturn(AbiKind kind) => kind switch
    {
        AbiKind.Void => "return;",
        AbiKind.Bool => "return false;",
        AbiKind.Opaque => "return nullptr;",
        AbiKind.StringView => "return HosihikariStringView{nullptr, 0};",
        AbiKind.ArrayView => "return HosihikariArrayView{nullptr, 0};",
        AbiKind.Shared => "return HosihikariSharedHandle{nullptr, nullptr, nullptr};",
        AbiKind.MapView => "return HosihikariArrayView{nullptr, 0};",
        AbiKind.F32 => "return 0.0f;",
        AbiKind.F64 => "return 0.0;",
        _ => "return 0;",
    };

    private static string FieldTarget(AbiFunction function)
    {
        var className = function.ClassCppName;
        var field = function.NativeMemberName;
        return function.Static
            ? $"{className}::{field}"
            : $"static_cast<{className}*>({SelfParameter})->{field}";
    }

    private static IEnumerable<string> BuildNativeArguments(AbiFunction function)
    {
        for (var index = 0; index < function.Parameters.Count; index++)
        {
            yield return NativeArgument(function, function.Parameters[index], index);
        }
    }

    private static string NativeArgument(
        AbiFunction function,
        AbiParameter parameter,
        int index,
        string? nameOverride = null)
    {
        var name = nameOverride ?? CppParameterName(parameter, index);
        if (parameter.IsMap)
        {
            var mapName = $"hs_map{index}";
            return parameter.IsReference ? mapName : $"std::move({mapName})";
        }

        if (parameter.IsVector)
        {
            if (parameter.VectorElementOwnership == ArrayElementOwnership.PairCopy)
            {
                return $"std::move(hs_vec{index})";
            }

            if (parameter.VectorElementKind == AbiKind.StringView)
            {
                var helper = AbiPlan.IsStringViewType(parameter.VectorElementType ?? "")
                    ? "hs_make_string_view_vector"
                    : "hs_make_string_vector";
                return $"{helper}({name}_data, {name}_count)";
            }

            return parameter.VectorElementOwnership switch
            {
                ArrayElementOwnership.RecordCopy =>
                    $"hs_make_record_vector<{parameter.VectorElementNativeType}>({name}_data, {name}_count)",
                ArrayElementOwnership.OptionalRecordCopy =>
                    $"hs_make_optional_record_vector<{parameter.VectorElementNativeType}>({name}_data, {name}_count)",
                ArrayElementOwnership.VariantCopy =>
                    $"hs_make_variant_vector<{parameter.VectorElementNativeType}>({name}_data, {name}_count)",
                _ => $"hs_make_vector<{parameter.VectorElementType}>({name}_data, {name}_count)",
            };
        }

        if (parameter.IsUniquePtrParam)
        {
            var pointee = parameter.NativePointee ?? "void";
            return $"std::unique_ptr<{pointee}>(static_cast<{pointee}*>({name}))";
        }

        if (parameter.SpecialValue != SpecialValueKind.None)
        {
            if (parameter.IsOptional)
            {
                var inner = parameter.OptionalInnerType ?? parameter.NativeType;
                return $"({name}_hasValue ? std::optional<{inner}>{{{SpecialParameterExpression(parameter, name)}}} : std::nullopt)";
            }

            return SpecialParameterExpression(parameter, name);
        }

        if (parameter.IsOptionalRef)
        {
            var inner = parameter.OptionalRefInnerType ?? parameter.NativeType;
            return $"({name}_hasValue ? optional_ref<{inner}>{{static_cast<{inner}*>({name})}} : optional_ref<{inner}>{{}})";
        }

        if (parameter.IsOptional && parameter.TimeConversion != TimeConversion.None)
        {
            var inner = parameter.OptionalInnerType ?? parameter.NativeType;
            return $"({name}_hasValue ? std::optional<{inner}>{{{TimeParameterExpression(parameter, name)}}} : std::nullopt)";
        }

        if (parameter.TimeConversion != TimeConversion.None)
        {
            return TimeParameterExpression(parameter, name);
        }

        if (parameter.IsOptional)
        {
            var inner = parameter.OptionalInnerType ?? parameter.NativeType;
            if (parameter.Kind == AbiKind.StringView)
            {
                var stringType = AbiPlan.IsStringViewType(inner)
                    ? "std::basic_string_view<char>"
                    : "std::basic_string<char>";
                return $"({name}_hasValue ? std::optional<{inner}>{{{stringType}({name}_data, {name}_size)}} : std::nullopt)";
            }

            if (parameter.Kind == AbiKind.Opaque)
            {
                return $"({name}_hasValue ? std::optional<{inner}>{{*static_cast<const {inner}*>({name})}} : std::nullopt)";
            }

            return $"({name}_hasValue ? std::optional<{inner}>{{static_cast<{inner}>({name})}} : std::nullopt)";
        }

        switch (parameter.Kind)
        {
            case AbiKind.StringView:
                var stringType = AbiPlan.IsStringViewType(parameter.NativeType)
                    ? "std::basic_string_view<char>"
                    : "std::basic_string<char>";
                return $"{stringType}({name}_data, {name}_size)";

            case AbiKind.Shared:
            {
                var pointee = parameter.NativePointee ?? "void";
                var helper = parameter.IsWeakPtr ? "hs_weak_from_handle" : "hs_shared_from_handle";
                return $"{helper}<{pointee}>({name})";
            }

            case AbiKind.Opaque:
            {
                var pointee = parameter.NativePointee ?? "void";
                var constPrefix = parameter.IsConst ? "const " : "";
                return parameter.IsReference
                    ? (parameter.IsRValueReference
                        ? $"std::move(*static_cast<{constPrefix}{pointee}*>({name}))"
                        : $"*static_cast<{constPrefix}{pointee}*>({name})")
                    : $"static_cast<{constPrefix}{pointee}*>({name})";
            }

            case AbiKind.Callback:
                return BuildCallbackArgument(function, parameter, index, name);

            default:
                return $"static_cast<{parameter.NativeType}>({name})";
        }
    }

    private static string CallbackSuffix(AbiFunction function, int index) =>
        function.CppName + "_cb" + index.ToString(CultureInfo.InvariantCulture);

    private static string BuildCallbackArgument(
        AbiFunction function,
        AbiParameter parameter,
        int index,
        string name)
    {
        var suffix = CallbackSuffix(function, index);
        return parameter.Callback!.NativeType
            + "(hs_cb_closure_" + suffix
            + "{std::make_shared<hs_cb_state_" + suffix
            + ">(reinterpret_cast<hs_cb_invoke_" + suffix + ">(" + name + "_invoke), "
            + name + "_userData, reinterpret_cast<hs_cb_release_" + suffix + ">(" + name + "_release))})";
    }

    private static IEnumerable<string> EmitCallbackSupport(
        AbiFunction function,
        int index,
        AbiParameter parameter)
    {
        var callback = parameter.Callback!;
        var suffix = CallbackSuffix(function, index);
        var invokeReturn = callback.ReturnKind == AbiKind.Void
            ? "void"
            : AbiPlan.CppType(callback.ReturnKind);
        var abiParameters = new List<string> { "void* userData" };
        for (var argumentIndex = 0; argumentIndex < callback.Arguments.Count; argumentIndex++)
        {
            var argument = callback.Arguments[argumentIndex];
            switch (argument.Kind)
            {
                case AbiKind.StringView:
                    abiParameters.Add($"const char* arg{argumentIndex}_data");
                    abiParameters.Add($"std::size_t arg{argumentIndex}_size");
                    break;
                case AbiKind.Opaque:
                    abiParameters.Add($"void* arg{argumentIndex}");
                    break;
                default:
                    abiParameters.Add($"{AbiPlan.CppType(argument.Kind)} arg{argumentIndex}");
                    break;
            }
        }

        yield return $"using hs_cb_invoke_{suffix} = {invokeReturn} (*)({string.Join(", ", abiParameters)});";
        yield return $"using hs_cb_release_{suffix} = void (*)(void*);";
        yield return $"struct hs_cb_state_{suffix}";
        yield return "{";
        yield return $"    hs_cb_invoke_{suffix} invoke;";
        yield return "    void* userData;";
        yield return $"    hs_cb_release_{suffix} release;";
        yield return $"    hs_cb_state_{suffix}(hs_cb_invoke_{suffix} invoke_, void* userData_, hs_cb_release_{suffix} release_)";
        yield return "        : invoke(invoke_), userData(userData_), release(release_) {}";
        yield return $"    ~hs_cb_state_{suffix}() {{ if (release) {{ release(userData); }} }}";
        yield return "};";
        yield return $"struct hs_cb_closure_{suffix}";
        yield return "{";
        yield return $"    std::shared_ptr<hs_cb_state_{suffix}> state;";
        var nativeParameters = new List<string>();
        for (var argumentIndex = 0; argumentIndex < callback.Arguments.Count; argumentIndex++)
        {
            nativeParameters.Add($"{callback.Arguments[argumentIndex].NativeType} arg{argumentIndex}");
        }

        yield return $"    {callback.ReturnNativeType} operator()({string.Join(", ", nativeParameters)}) const";
        yield return "    {";
        for (var argumentIndex = 0; argumentIndex < callback.Arguments.Count; argumentIndex++)
        {
            if (callback.Arguments[argumentIndex].Kind == AbiKind.StringView)
            {
                yield return $"        HosihikariStringView hs_arg{argumentIndex}{{arg{argumentIndex}.data(), arg{argumentIndex}.size()}};";
            }
        }

        var callArguments = new List<string> { "state->userData" };
        for (var argumentIndex = 0; argumentIndex < callback.Arguments.Count; argumentIndex++)
        {
            var argument = callback.Arguments[argumentIndex];
            var argumentName = "arg" + argumentIndex.ToString(CultureInfo.InvariantCulture);
            switch (argument.Kind)
            {
                case AbiKind.StringView:
                    callArguments.Add($"hs_arg{argumentIndex}.data");
                    callArguments.Add($"hs_arg{argumentIndex}.size");
                    break;
                case AbiKind.Opaque:
                    if (argument.IsPointer)
                    {
                        callArguments.Add(argument.IsConst
                            ? $"const_cast<void*>(static_cast<void const*>({argumentName}))"
                            : $"static_cast<void*>({argumentName})");
                    }
                    else
                    {
                        callArguments.Add(argument.IsConst
                            ? $"const_cast<void*>(static_cast<void const*>(std::addressof({argumentName})))"
                            : $"static_cast<void*>(std::addressof({argumentName}))");
                    }

                    break;
                default:
                    callArguments.Add($"static_cast<{AbiPlan.CppType(argument.Kind)}>({argumentName})");
                    break;
            }
        }

        var invoke = $"state->invoke({string.Join(", ", callArguments)})";
        if (callback.ReturnKind == AbiKind.Void)
        {
            yield return $"        {invoke};";
        }
        else
        {
            yield return $"        return static_cast<{callback.ReturnNativeType}>({invoke});";
        }

        yield return "    }";
        yield return "};";
    }

    /// <summary>
    /// The typed C++ optional used for symbol dispatch. A user-provided copy constructor makes
    /// the native optional non-trivial, so the compiler must own the call ABI and destruction.
    /// </summary>
    private static LayoutInfo? OptionalRecordLayout(
        string? inner,
        IReadOnlyDictionary<string, LayoutInfo> layoutsByQualifiedName)
    {
        if (inner is null)
        {
            return null;
        }

        var name = inner.Replace("const ", "", StringComparison.Ordinal).Replace(" const", "", StringComparison.Ordinal).Trim();
        return layoutsByQualifiedName.TryGetValue(name, out var layout)
            || layoutsByQualifiedName.TryGetValue(AbiPlan.CompactTemplateName(name), out layout)
                ? layout
                : null;
    }

    private static string? SymbolOptionalType(
        AbiParameter parameter,
        IReadOnlyDictionary<string, LayoutInfo> layoutsByQualifiedName)
    {
        if (!parameter.IsOptional || parameter.IsOptionalRef)
        {
            return null;
        }

        if (parameter.IsOptionalRecord)
        {
            var layout = OptionalRecordLayout(parameter.OptionalInnerType, layoutsByQualifiedName);
            if (layout is not { Size: > 0 })
            {
                return null;
            }

            var align = layout.Align > 0 ? layout.Align : 8;
            return $"std::optional<hs_blob<{layout.Size.ToString(CultureInfo.InvariantCulture)}, {align.ToString(CultureInfo.InvariantCulture)}>>";
        }

        if (parameter.Kind == AbiKind.StringView)
        {
            var inner = AbiPlan.IsStringViewType(parameter.OptionalInnerType ?? parameter.NativeType)
                ? "std::basic_string_view<char>"
                : "std::basic_string<char>";
            return $"std::optional<{inner}>";
        }

        return AbiPlan.IsSymbolScalarKind(parameter.Kind)
            ? $"std::optional<{AbiPlan.CppType(parameter.Kind)}>"
            : null;
    }

    private static string? SymbolOptionalReturnType(
        AbiFunction function,
        IReadOnlyDictionary<string, LayoutInfo> layouts)
    {
        if (!function.ReturnOptional)
        {
            return null;
        }

        if (function.ReturnOptionalRecord
            && function.ReturnDeclarationId is not null
            && layouts.TryGetValue(function.ReturnDeclarationId, out var layout)
            && layout.Size > 0)
        {
            var align = layout.Align > 0 ? layout.Align : 8;
            return $"std::optional<hs_blob<{layout.Size.ToString(CultureInfo.InvariantCulture)}, {align.ToString(CultureInfo.InvariantCulture)}>>";
        }

        if (function.ReturnKind == AbiKind.StringView)
        {
            var inner = AbiPlan.IsStringViewType(function.NativeReturnType)
                ? "std::basic_string_view<char>"
                : "std::basic_string<char>";
            return $"std::optional<{inner}>";
        }

        return AbiPlan.IsSymbolScalarKind(function.ReturnKind)
            ? $"std::optional<{AbiPlan.CppType(function.ReturnKind)}>"
            : null;
    }

    private static string? SymbolOptionalArgument(AbiParameter parameter, int index)
    {
        if (!parameter.IsOptional || parameter.IsOptionalRef)
        {
            return null;
        }

        var name = CppParameterName(parameter, index);
        if (parameter.Kind == AbiKind.StringView)
        {
            var inner = AbiPlan.IsStringViewType(parameter.OptionalInnerType ?? parameter.NativeType)
                ? "std::basic_string_view<char>"
                : "std::basic_string<char>";
            return $"{inner}({name}_data, {name}_size)";
        }

        return AbiPlan.IsSymbolScalarKind(parameter.Kind)
            ? $"static_cast<{AbiPlan.CppType(parameter.Kind)}>({name})"
            : null;
    }

    private static string CppParameterName(AbiParameter parameter, int index)
    {
        var name = string.IsNullOrWhiteSpace(parameter.Name)
            ? "arg" + index.ToString(CultureInfo.InvariantCulture)
            : parameter.Name;
        return name;
    }

    private static void WriteSymbolSurface(
        string directory,
        List<string> header,
        string manifestHash,
        IrConfiguration configuration,
        string surface,
        IReadOnlyList<AbiFunction> functions,
        IReadOnlyList<IrRecord> records,
        string targetModule,
        IrManifest manifest)
    {
        var members = records.OfType<MemberRecord>()
            .Where(member => string.Equals(member.Configuration, configuration.Id, StringComparison.Ordinal))
            .GroupBy(member => member.Id, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.First(), StringComparer.Ordinal);
        var layouts = records.OfType<VariantRecord>()
            .Where(variant => string.Equals(variant.Configuration, configuration.Id, StringComparison.Ordinal))
            .Where(variant => variant.Layout is not null)
            .GroupBy(variant => variant.DeclarationId, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.First().Layout!, StringComparer.Ordinal);

        var source = new List<string>
        {
            "// <auto-generated/>",
            $"// ir-manifest-sha256: {manifestHash}",
            "#include \"binding_table.h\"",
            "",
            "#include <cstddef>",
            "#include <cstdint>",
            "#include <cstring>",
            "#include <exception>",
            "#include <memory>",
            "#include <new>",
            "#include <optional>",
            "#include <stdexcept>",
            "#include <string>",
            "#include <string_view>",
            "#include <typeindex>",
            "#include <utility>",
            "#include <vector>",
            "#ifdef _WIN32",
            "#include <windows.h>",
            "#else",
            "#include <dlfcn.h>",
            "#include <link.h>",
            "#endif",
            "",
            "namespace {",
            "",
            "using hosihikari::abi::setLastError;",
            "thread_local std::string g_stringResult;",
            "",
        };

        AppendSymbolResolution(source, configuration.Os, targetModule);

        source.Add("");
        source.Add("inline void* hs_allocate(std::size_t size, std::size_t align)");
        source.Add("{");
        source.Add("    return align > 16");
        source.Add("        ? ::operator new(size, std::align_val_t(align))");
        source.Add("        : ::operator new(size);");
        source.Add("}");
        source.Add("inline void hs_deallocate(void* pointer, std::size_t align) noexcept");
        source.Add("{");
        source.Add("    if (pointer == nullptr) { return; }");
        source.Add("    if (align > 16) { ::operator delete(pointer, std::align_val_t(align)); }");
        source.Add("    else { ::operator delete(pointer); }");
        source.Add("}");

        var stringDestructor = StringDestructor(manifest, configuration);
        if (stringDestructor is not null)
        {
            source.Add("");
            source.Add("inline void hs_destroy_string(std::basic_string<char>* value)");
            source.Add("{");
            source.Add("    using HsDestroy = void (*)(std::basic_string<char>*);");
            source.Add($"    static HsDestroy const destroy = reinterpret_cast<HsDestroy>(hs_resolve({stringDestructor.Value.Offset}, {CppLiteral(stringDestructor.Value.Symbol)}));");
            source.Add("    if (destroy != nullptr) { destroy(value); } else { value->~basic_string(); }");
            source.Add("}");
        }

        source.Add("");
        source.Add("template <class T, class U>");
        source.Add("std::vector<T> hs_make_vector(U const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<T> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.push_back(static_cast<T>(data[i])); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("inline std::vector<std::basic_string<char>> hs_make_string_vector(HosihikariStringView const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<std::basic_string<char>> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.emplace_back(data[i].data, data[i].size); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("inline std::vector<std::basic_string_view<char>> hs_make_string_view_vector(HosihikariStringView const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<std::basic_string_view<char>> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i) { result.emplace_back(data[i].data, data[i].size); }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("template <std::size_t Size, std::size_t Align>");
        source.Add("struct hs_blob");
        source.Add("{");
        source.Add("    alignas(Align) unsigned char data[Size];");
        source.Add("};");
        source.Add("template <std::size_t Size, std::size_t Align>");
        source.Add("std::vector<hs_blob<Size, Align>> hs_make_blob_vector(void* const* data, std::size_t count)");
        source.Add("{");
        source.Add("    std::vector<hs_blob<Size, Align>> result;");
        source.Add("    result.reserve(count);");
        source.Add("    for (std::size_t i = 0; i < count; ++i)");
        source.Add("    {");
        source.Add("        hs_blob<Size, Align> blob{};");
        source.Add("        if (data[i] != nullptr) { std::memcpy(blob.data, data[i], Size); }");
        source.Add("        result.push_back(blob);");
        source.Add("    }");
        source.Add("    return result;");
        source.Add("}");
        source.Add("struct hs_unique_void_deleter");
        source.Add("{");
        source.Add("    void operator()(void*) const noexcept {}");
        source.Add("};");
        source.Add("struct hs_shared_holder_base");
        source.Add("{");
        source.Add("    virtual ~hs_shared_holder_base() = default;");
        source.Add("    virtual std::shared_ptr<const void> hs_share() const = 0;");
        source.Add("    virtual std::type_index hs_type() const = 0;");
        source.Add("};");
        source.Add("");
        source.Add("template <class T>");
        source.Add("struct hs_shared_holder final : hs_shared_holder_base");
        source.Add("{");
        source.Add("    explicit hs_shared_holder(std::shared_ptr<T> value) : value(std::move(value)) {}");
        source.Add("    std::shared_ptr<T> value;");
        source.Add("    std::shared_ptr<const void> hs_share() const override");
        source.Add("    {");
        source.Add("        return std::shared_ptr<const void>(value, value.get());");
        source.Add("    }");
        source.Add("");
        source.Add("    std::type_index hs_type() const override { return std::type_index(typeid(T)); }");
        source.Add("};");
        source.Add("");
        source.Add("template <class T>");
        source.Add("void hs_release_shared_holder(void* holder)");
        source.Add("{");
        source.Add("    delete static_cast<hs_shared_holder<T>*>(holder);");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("HosihikariSharedHandle hs_make_shared_handle(std::shared_ptr<T> value)");
        source.Add("{");
        source.Add("    if (!value) { return HosihikariSharedHandle{nullptr, nullptr, nullptr}; }");
        source.Add("    auto* holder = new hs_shared_holder<T>(std::move(value));");
        source.Add("    return HosihikariSharedHandle{holder, const_cast<void*>(static_cast<void const*>(holder->value.get())), &hs_release_shared_holder<T>};");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("HosihikariSharedHandle hs_make_non_owner_handle(std::shared_ptr<T> value)");
        source.Add("{");
        source.Add("    if (!value) { return HosihikariSharedHandle{nullptr, nullptr, nullptr}; }");
        source.Add("    void* target = *reinterpret_cast<void**>(value.get());");
        source.Add("    auto* holder = new hs_shared_holder<T>(std::move(value));");
        source.Add("    return HosihikariSharedHandle{holder, target, &hs_release_shared_holder<T>};");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("std::shared_ptr<T> hs_shared_from_handle(HosihikariSharedHandle handle)");
        source.Add("{");
        source.Add("    if (handle.holder == nullptr) { return {}; }");
        source.Add("    auto* holder = static_cast<hs_shared_holder_base*>(handle.holder);");
        source.Add("    if (holder->hs_type() != std::type_index(typeid(T)))");
        source.Add("    {");
        source.Add("        throw std::invalid_argument(\"shared handle type mismatch\");");
        source.Add("    }");
        source.Add("    using Value = std::remove_const_t<T>;");
        source.Add("    auto shared = holder->hs_share();");
        source.Add("    auto* raw = const_cast<Value*>(static_cast<Value const*>(shared.get()));");
        source.Add("    return std::shared_ptr<T>(std::move(shared), raw);");
        source.Add("}");
        source.Add("");
        source.Add("template <class T>");
        source.Add("std::weak_ptr<T> hs_weak_from_handle(HosihikariSharedHandle handle)");
        source.Add("{");
        source.Add("    return std::weak_ptr<T>(hs_shared_from_handle<T>(handle));");
        source.Add("}");
        source.Add("");

        var layoutsByQualifiedName = new Dictionary<string, LayoutInfo>(StringComparer.Ordinal);
        foreach (var declaration in records.OfType<DeclarationRecord>())
        {
            if (layouts.TryGetValue(declaration.Id, out var declarationLayout))
            {
                layoutsByQualifiedName[declaration.QualifiedName] = declarationLayout;
            }
        }

        foreach (var function in functions)
        {
            foreach (var line in EmitSymbolFunction(function, configuration, members, layouts, layoutsByQualifiedName, stringDestructor is not null))
            {
                source.Add(line);
            }

            source.Add("");
        }

        source.Add("const HosihikariBindingTableV1 kTable{");
        source.Add("    std::uint32_t{1},");
        source.Add("    static_cast<std::uint32_t>(sizeof(HosihikariBindingTableV1)),");
        foreach (var function in functions)
        {
            source.Add($"    &{function.CppName},");
        }

        source.Add("};");
        source.Add("");
        source.Add("}  // namespace");
        source.Add("");
        source.Add("extern \"C\" HOSIHIKARI_SHIM_EXPORT const HosihikariBindingTableV1* hosihikari_get_binding_table_v1()");
        source.Add("{");
        source.Add("    return &kTable;");
        source.Add("}");
        source.Add("");
        source.Add("extern \"C\" HOSIHIKARI_SHIM_EXPORT const char* hosihikari_get_last_error() noexcept");
        source.Add("{");
        source.Add("    return hosihikari::abi::lastError();");
        source.Add("}");

        Write(directory, header, source);
    }

    private static void AppendSymbolResolution(List<string> source, string os, string targetModule)
    {
        source.Add("void* hs_resolve(std::uintptr_t offset, const char* symbol);");
        source.Add("");

        if (string.Equals(os, "windows", StringComparison.Ordinal))
        {
            var moduleNames = new List<string> { targetModule };
            if (!Path.HasExtension(targetModule))
            {
                moduleNames.Add(targetModule + ".exe");
                moduleNames.Add(targetModule + ".dll");
            }

            source.Add("std::uintptr_t hs_moduleBase()");
            source.Add("{");
            source.Add("    static std::uintptr_t const base = []");
            source.Add("    {");
            source.Add("        HMODULE module = nullptr;");
            foreach (var moduleName in moduleNames)
            {
                source.Add($"        if (module == nullptr) {{ module = ::GetModuleHandleW(L\"{EscapeCpp(moduleName)}\"); }}");
            }

            source.Add("        if (module == nullptr) { module = ::GetModuleHandleW(nullptr); }");
            source.Add("        return reinterpret_cast<std::uintptr_t>(module);");
            source.Add("    }();");
            source.Add("    return base;");
            source.Add("}");
            source.Add("");
            source.Add("void* hs_resolve(std::uintptr_t offset, const char* symbol)");
            source.Add("{");
            source.Add("    std::uintptr_t const base = hs_moduleBase();");
            source.Add("    if (offset != 0 && base != 0) { return reinterpret_cast<void*>(base + offset); }");
            source.Add("    HMODULE const module = reinterpret_cast<HMODULE>(base);");
            source.Add("    if (module == nullptr || symbol == nullptr || *symbol == '\\0') { return nullptr; }");
            source.Add("    return reinterpret_cast<void*>(::GetProcAddress(module, symbol));");
            source.Add("}");
            source.Add("");
            return;
        }

        source.Add("struct HsModuleContext");
        source.Add("{");
        source.Add("    char const* name;");
        source.Add("    std::uintptr_t base;");
        source.Add("    bool found;");
        source.Add("};");
        source.Add("");
        source.Add("int hs_moduleCallback(struct dl_phdr_info* info, std::size_t, void* data)");
        source.Add("{");
        source.Add("    auto* context = static_cast<HsModuleContext*>(data);");
        source.Add("    char const* name = info->dlpi_name != nullptr ? info->dlpi_name : \"\";");
        source.Add("    char const* slash = std::strrchr(name, '/');");
        source.Add("    char const* baseName = slash != nullptr ? slash + 1 : name;");
        source.Add("    char const* requestedSlash = std::strrchr(context->name, '/');");
        source.Add("    char const* requested = requestedSlash != nullptr ? requestedSlash + 1 : context->name;");
        source.Add("    bool const mainModule = *baseName == '\\0';");
        source.Add("    if ((mainModule && std::strcmp(requested, \"bedrock_server\") == 0)");
        source.Add("        || std::strcmp(baseName, requested) == 0)");
        source.Add("    {");
        source.Add("        context->base = static_cast<std::uintptr_t>(info->dlpi_addr);");
        source.Add("        context->found = true;");
        source.Add("        return 1;");
        source.Add("    }");
        source.Add("");
        source.Add("    return 0;");
        source.Add("}");
        source.Add("");
        source.Add("std::uintptr_t hs_moduleBase()");
        source.Add("{");
        source.Add("    static std::uintptr_t const base = []");
        source.Add("    {");
        source.Add($"        HsModuleContext context{{\"{EscapeCpp(targetModule)}\", 0, false}};");
        source.Add("        ::dl_iterate_phdr(&hs_moduleCallback, &context);");
        source.Add("        return context.found ? context.base : 0;");
        source.Add("    }();");
        source.Add("    return base;");
        source.Add("}");
        source.Add("");
        source.Add("void* hs_dynamicModule()");
        source.Add("{");
        source.Add("    static void* const handle = []");
        source.Add("    {");
        source.Add($"        void* loaded = ::dlopen(\"{EscapeCpp(targetModule)}\", RTLD_LAZY | RTLD_NOLOAD);");
        source.Add("        if (loaded == nullptr)");
        source.Add("        {");
        source.Add($"            loaded = ::dlopen(\"{EscapeCpp(targetModule)}\", RTLD_LAZY | RTLD_GLOBAL);");
        source.Add("        }");
        source.Add("");
        source.Add("        return loaded;");
        source.Add("    }();");
        source.Add("    return handle;");
        source.Add("}");
        source.Add("");
        source.Add("void* hs_resolve(std::uintptr_t offset, const char* symbol)");
        source.Add("{");
        source.Add("    std::uintptr_t const base = hs_moduleBase();");
        source.Add("    if (offset != 0 && base != 0) { return reinterpret_cast<void*>(base + offset); }");
        source.Add("    if (symbol == nullptr || *symbol == '\\0') { return nullptr; }");
        source.Add("    if (void* const handle = hs_dynamicModule())");
        source.Add("    {");
        source.Add("        if (void* const address = ::dlsym(handle, symbol)) { return address; }");
        source.Add("    }");
        source.Add("");
        source.Add("    return ::dlsym(RTLD_DEFAULT, symbol);");
        source.Add("}");
        source.Add("");
    }

    private static IEnumerable<string> EmitSymbolFunction(
        AbiFunction function,
        IrConfiguration configuration,
        IReadOnlyDictionary<string, MemberRecord> members,
        IReadOnlyDictionary<string, LayoutInfo> layouts,
        IReadOnlyDictionary<string, LayoutInfo> layoutsByQualifiedName,
        bool destroyStringViaGame)
    {
        var returnType = AbiPlan.CppType(function.ReturnKind);
        var parameters = new List<string>();
        if (function.Kind != AbiFunctionKind.Create && !function.Static)
        {
            parameters.Add("void* hs_self");
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.IsVector)
            {
                continue;
            }

            var name = CppParameterName(parameter, index);
            if (parameter.Kind == AbiKind.StringView)
            {
                parameters.Add($"const char* {name}_data");
                parameters.Add($"std::size_t {name}_size");
            }
            else if (parameter.Kind == AbiKind.Opaque)
            {
                parameters.Add($"void* {name}");
            }
            else
            {
                parameters.Add($"{AbiPlan.CppType(parameter.Kind)} {name}");
            }
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (!parameter.IsVector)
            {
                continue;
            }

            var name = CppParameterName(parameter, index);
            if (parameter.VectorElementKind == AbiKind.Opaque)
            {
                parameters.Add($"void* const* {name}_data");
            }
            else
            {
                var elementType = parameter.VectorElementKind == AbiKind.StringView
                    ? "HosihikariStringView"
                    : AbiPlan.CppType(parameter.VectorElementKind);
                parameters.Add($"const {elementType}* {name}_data");
            }

            parameters.Add($"std::size_t {name}_count");
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.IsOptional)
            {
                parameters.Add($"bool {CppParameterName(parameter, index)}_hasValue");
            }
        }

        if (function.NeedsPresenceFlag)
        {
            parameters.Add("bool* hs_hasValue");
        }

        yield return $"static {returnType} {function.CppName}({string.Join(", ", parameters)}) try";
        yield return "{";

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.Kind != AbiKind.StringView)
            {
                continue;
            }

            var name = CppParameterName(parameter, index);
            var stringType = AbiPlan.IsStringViewType(parameter.NativeType)
                ? "std::basic_string_view<char>"
                : "std::basic_string<char>";
            yield return $"    {stringType} hs_str{index}({name}_data, {name}_size);";
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            var optionalType = SymbolOptionalType(parameter, layoutsByQualifiedName);
            if (optionalType is null)
            {
                continue;
            }

            var name = CppParameterName(parameter, index);
            if (parameter.IsOptionalRecord)
            {
                var optionalRecordLayout = OptionalRecordLayout(parameter.OptionalInnerType, layoutsByQualifiedName)!;
                var size = optionalRecordLayout.Size.ToString(CultureInfo.InvariantCulture);
                var align = (optionalRecordLayout.Align > 0 ? optionalRecordLayout.Align : 8).ToString(CultureInfo.InvariantCulture);
                yield return $"    {optionalType} hs_opt{index};";
                yield return $"    if ({name}_hasValue) {{ hs_blob<{size}, {align}> hs_blob{index}{{}}; std::memcpy(hs_blob{index}.data, {name}, {size}); hs_opt{index} = hs_blob{index}; }}";
                continue;
            }

            yield return $"    {optionalType} hs_opt{index};";
            yield return $"    if ({name}_hasValue) {{ hs_opt{index} = {SymbolOptionalArgument(parameter, index)}; }}";
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.Kind != AbiKind.Shared)
            {
                continue;
            }

            var name = CppParameterName(parameter, index);
            if (parameter.IsWeakPtr)
            {
                yield return $"    auto hs_weak{index} = hs_weak_from_handle<void>({name});";
            }
            else
            {
                yield return $"    auto hs_shared{index} = hs_shared_from_handle<void>({name});";
            }
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (!parameter.IsVector)
            {
                continue;
            }

            var name = CppParameterName(parameter, index);
            if (parameter.VectorElementKind == AbiKind.StringView)
            {
                var helper = AbiPlan.IsStringViewType(parameter.VectorElementType ?? "")
                    ? "hs_make_string_view_vector"
                    : "hs_make_string_vector";
                yield return $"    auto hs_vec{index} = {helper}({name}_data, {name}_count);";
                continue;
            }

            if (parameter.VectorElementKind == AbiKind.Opaque)
            {
                if (parameter.VectorElementOwnership == ArrayElementOwnership.None)
                {
                    // Pointer elements stay pointer-sized and surface as nint[].
                    yield return $"    auto hs_vec{index} = hs_make_vector<void*>({name}_data, {name}_count);";
                    continue;
                }

                if (parameter.VectorElementNativeType is null
                    || !layoutsByQualifiedName.TryGetValue(parameter.VectorElementNativeType, out var elementLayout)
                    || elementLayout.Size <= 0)
                {
                    yield return $"    setLastError(\"the layout of {EscapeCpp(parameter.VectorElementNativeType ?? "the vector element")} is unavailable\");";
                    yield return "    " + DefaultReturn(function.ReturnKind);
                    foreach (var line in SymbolCatchTail(function.ReturnKind))
                    {
                        yield return line;
                    }

                    yield break;
                }

                var elementAlign = elementLayout.Align > 0 ? elementLayout.Align : 8;
                yield return $"    auto hs_vec{index} = hs_make_blob_vector<{elementLayout.Size.ToString(CultureInfo.InvariantCulture)}, {elementAlign.ToString(CultureInfo.InvariantCulture)}>({name}_data, {name}_count);";
                continue;
            }

            yield return $"    auto hs_vec{index} = hs_make_vector<{AbiPlan.CppType(parameter.VectorElementKind)}>({name}_data, {name}_count);";
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (!parameter.IsByValueRecord)
            {
                continue;
            }

            if (parameter.ByValueDeclarationId is null
                || !layouts.TryGetValue(parameter.ByValueDeclarationId, out var parameterLayout)
                || parameterLayout.Size <= 0)
            {
                yield return $"    setLastError(\"the layout of {EscapeCpp(parameter.NativeType)} is unavailable\");";
                yield return "    " + DefaultReturn(function.ReturnKind);
                foreach (var line in SymbolCatchTail(function.ReturnKind))
                {
                    yield return line;
                }

                yield break;
            }

            if (parameterLayout.Size <= 8 && parameter.ByValueTriviallyCopyable)
            {
                // Small trivial records are passed in a register; the call argument reads
                // the handle's bytes directly.
                continue;
            }

            var align = parameterLayout.Align > 0 ? parameterLayout.Align : 8;
            var name = CppParameterName(parameter, index);
            yield return $"    alignas({align.ToString(CultureInfo.InvariantCulture)}) unsigned char hs_arg{index}Storage[{parameterLayout.Size.ToString(CultureInfo.InvariantCulture)}];";
            yield return $"    std::memcpy(hs_arg{index}Storage, {name}, static_cast<std::size_t>({parameterLayout.Size.ToString(CultureInfo.InvariantCulture)}));";
        }

        if (function.FieldBitOffset is { } fieldBits
            && function.Kind is AbiFunctionKind.Get or AbiFunctionKind.Set)
        {
            var byteOffset = fieldBits / 8;
            if (function.Kind == AbiFunctionKind.Get)
            {
                if (function.ReturnKind == AbiKind.Opaque)
                {
                    yield return $"    return *reinterpret_cast<void* const*>(static_cast<unsigned char const*>(hs_self) + {byteOffset.ToString(CultureInfo.InvariantCulture)});";
                }
                else
                {
                    var nativeType = AbiPlan.CppType(function.ReturnKind);
                    yield return $"    return static_cast<{returnType}>(*reinterpret_cast<{nativeType} const*>(static_cast<unsigned char const*>(hs_self) + {byteOffset.ToString(CultureInfo.InvariantCulture)}));";
                }
            }
            else
            {
                var parameter = function.Parameters[0];
                var name = CppParameterName(parameter, 0);
                if (parameter.Kind == AbiKind.Opaque)
                {
                    yield return $"    *reinterpret_cast<void**>(static_cast<unsigned char*>(hs_self) + {byteOffset.ToString(CultureInfo.InvariantCulture)}) = {name};";
                }
                else
                {
                    var nativeType = AbiPlan.CppType(parameter.Kind);
                    yield return $"    *reinterpret_cast<{nativeType}*>(static_cast<unsigned char*>(hs_self) + {byteOffset.ToString(CultureInfo.InvariantCulture)}) = static_cast<{nativeType}>({name});";
                }
            }

            foreach (var line in SymbolCatchTail(function.ReturnKind))
            {
                yield return line;
            }

            yield break;
        }

        MemberRecord? entry = null;
        if (function.Kind == AbiFunctionKind.Destroy)
        {
            entry = members.Values.FirstOrDefault(member =>
                    string.Equals(member.DeclarationId, function.DeclarationId, StringComparison.Ordinal)
                    && string.Equals(member.Kind, "destructor", StringComparison.Ordinal)
                    && string.Equals(member.Access, "public", StringComparison.Ordinal)
                    && HasDispatchSymbol(member))
                ?? members.Values.FirstOrDefault(member =>
                    string.Equals(member.DeclarationId, function.DeclarationId, StringComparison.Ordinal)
                    && string.Equals(member.Kind, "destructor", StringComparison.Ordinal)
                    && string.Equals(member.Access, "public", StringComparison.Ordinal));
        }
        else if (function.MemberId is not null)
        {
            members.TryGetValue(function.MemberId, out entry);
        }

        var virtualCall = function.Kind == AbiFunctionKind.Method
            && !function.Static
            && entry is { Virtual: true, VTableIndex: not null };
        LayoutInfo? layout = null;
        if (function.Kind is AbiFunctionKind.Create or AbiFunctionKind.Destroy)
        {
            layouts.TryGetValue(function.DeclarationId, out layout);
        }

        var hasTarget = virtualCall
            || entry is not null && (!string.IsNullOrWhiteSpace(entry.Symbol) || entry.Rva is not null || entry.Address is not null);
        if (!hasTarget && function.Kind != AbiFunctionKind.Destroy)
        {
            yield return $"    setLastError(\"symbol dispatch has no entry for {EscapeCpp(function.DeclarationId)} in {EscapeCpp(configuration.Id)}\");";
            yield return "    " + DefaultReturn(function.ReturnKind);
            foreach (var line in SymbolCatchTail(function.ReturnKind))
            {
                yield return line;
            }

            yield break;
        }

        if (function.Kind == AbiFunctionKind.Create)
        {
            if (layout is null || layout.Size <= 0)
            {
                yield return $"    setLastError(\"the layout of {EscapeCpp(function.DeclarationId)} is unavailable\");";
                yield return "    " + DefaultReturn(function.ReturnKind);
                foreach (var line in SymbolCatchTail(function.ReturnKind))
                {
                    yield return line;
                }

                yield break;
            }
        }

        if (virtualCall)
        {
            // The IR index is relative to the address point: Windows records the raw slot,
            // and the Linux reader subtracts the two Itanium prefix entries already.
            var index = entry!.VTableIndex!.Value;
            yield return "    auto* const hs_vtable = *reinterpret_cast<void***>(hs_self);";
            yield return $"    auto const hs_target = hs_vtable[{index.ToString(CultureInfo.InvariantCulture)}];";
        }
        else if (entry is not null)
        {
            var (offset, symbol) = SymbolFacts(entry, configuration.Os);
            if (function.Kind == AbiFunctionKind.Destroy)
            {
                yield return $"    auto const hs_dtor = hs_resolve({offset}, {CppLiteral(symbol)});";
            }
            else
            {
                yield return $"    auto const hs_target = hs_resolve({offset}, {CppLiteral(symbol)});";
            }
        }
        else if (function.Kind == AbiFunctionKind.Destroy)
        {
            yield return "    void const* const hs_dtor = nullptr;";
        }
        else
        {
            yield return "    void const* const hs_target = nullptr;";
        }

        if (function.Kind != AbiFunctionKind.Destroy)
        {
            yield return "    if (hs_target == nullptr)";
            yield return "    {";
            yield return "        setLastError(\"symbol was not resolved\");";
            yield return "        " + DefaultReturn(function.ReturnKind);
            yield return "    }";
        }

        if (function.Kind == AbiFunctionKind.Create)
        {
            var align = layout!.Align > 0 ? layout.Align : 8;
            yield return $"    auto* const hs_memory = static_cast<void*>(hs_allocate(static_cast<std::size_t>({layout.Size.ToString(CultureInfo.InvariantCulture)}), {align.ToString(CultureInfo.InvariantCulture)}));";
        }

        var ownedRecordReturn = function.Kind == AbiFunctionKind.Method
            && function.ReturnKind == AbiKind.Opaque
            && function.ReturnOwned
            && !function.ReturnUniquePtr
            && !function.ReturnOptional
            && !function.NativeReturnType.TrimEnd().EndsWith("*", StringComparison.Ordinal)
            && !function.NativeReturnType.TrimEnd().EndsWith("&", StringComparison.Ordinal);
        LayoutInfo? returnLayout = null;
        if (ownedRecordReturn && function.ReturnDeclarationId is not null)
        {
            layouts.TryGetValue(function.ReturnDeclarationId, out returnLayout);
        }

        var smallRecordReturn = ownedRecordReturn
            && function.ReturnTriviallyCopyable
            && returnLayout is { Size: <= 8 };
        var largeRecordReturn = ownedRecordReturn && !smallRecordReturn;
        var returnNeedsCopy = largeRecordReturn && function.ReturnRequiresCopy;
        MemberRecord? returnCopyConstructor = null;
        MemberRecord? returnDestructor = null;
        if (returnNeedsCopy && function.ReturnDeclarationId is not null)
        {
            foreach (var member in members.Values.Where(member =>
                         string.Equals(member.DeclarationId, function.ReturnDeclarationId, StringComparison.Ordinal)))
            {
                if (member.Kind == "destructor"
                    && member.Access == "public"
                    && HasDispatchSymbol(member))
                {
                    returnDestructor = member;
                }
                else if (member.Kind == "constructor"
                    && member.Access == "public"
                    && IsCopyConstructorRecord(member, function.NativeReturnType)
                    && HasDispatchSymbol(member))
                {
                    returnCopyConstructor = member;
                }
            }
        }

        if (returnNeedsCopy && (returnCopyConstructor is null || returnDestructor is null))
        {
            yield return $"    setLastError(\"the copy or destructor symbol of {EscapeCpp(function.NativeReturnType)} is unavailable\");";
            yield return "    " + DefaultReturn(function.ReturnKind);
            foreach (var line in SymbolCatchTail(function.ReturnKind))
            {
                yield return line;
            }

            yield break;
        }

        if (ownedRecordReturn && (returnLayout is null || returnLayout.Size <= 0))
        {
            yield return $"    setLastError(\"the layout of {EscapeCpp(function.NativeReturnType)} is unavailable\");";
            yield return "    " + DefaultReturn(function.ReturnKind);
            foreach (var line in SymbolCatchTail(function.ReturnKind))
            {
                yield return line;
            }

            yield break;
        }

        // A vector return is read as a standard three-pointer vector view. Element bytes stay
        // valid until the caller copies them; queued records are released without destructors.
        var arrayReturn = function.ReturnKind == AbiKind.ArrayView;
        var borrowedVectorReturn = arrayReturn
            && (AbiPlan.IsPointerType(function.NativeReturnType)
                || AbiPlan.IsReferenceType(function.NativeReturnType));
        string? vectorElementType = null;
        LayoutInfo? vectorElementLayout = null;
        if (arrayReturn)
        {
            switch (function.ArrayElementKind)
            {
                case AbiKind.StringView:
                    vectorElementType = AbiPlan.IsStringViewType(function.ArrayElementType ?? "")
                        ? "std::basic_string_view<char>"
                        : "std::basic_string<char>";
                    break;
                case AbiKind.Opaque when function.ArrayElementOwnership == ArrayElementOwnership.None:
                    vectorElementType = "void*";
                    break;
                case AbiKind.Opaque:
                    if (function.ArrayElementNativeType is null
                        || !layoutsByQualifiedName.TryGetValue(function.ArrayElementNativeType, out vectorElementLayout)
                        || vectorElementLayout.Size <= 0)
                    {
                        yield return $"    setLastError(\"the layout of {EscapeCpp(function.ArrayElementNativeType ?? "the vector element")} is unavailable\");";
                        yield return "    " + DefaultReturn(function.ReturnKind);
                        foreach (var line in SymbolCatchTail(function.ReturnKind))
                        {
                            yield return line;
                        }

                        yield break;
                    }

                    var elementAlign = vectorElementLayout.Align > 0 ? vectorElementLayout.Align : 8;
                    vectorElementType = $"hs_blob<{vectorElementLayout.Size.ToString(CultureInfo.InvariantCulture)}, {elementAlign.ToString(CultureInfo.InvariantCulture)}>";
                    break;
                default:
                    vectorElementType = AbiPlan.CppType(function.ArrayElementKind);
                    break;
            }
        }

        var callParameters = new List<string>();
        if (!function.Static)
        {
            callParameters.Add("void*");
        }

        for (var index = 0; index < function.Parameters.Count; index++)
        {
            var parameter = function.Parameters[index];
            if (parameter.IsVector)
            {
                callParameters.Add("void*");
                continue;
            }

            var optionalType = SymbolOptionalType(parameter, layoutsByQualifiedName);
            if (optionalType is not null)
            {
                callParameters.Add(optionalType);
                continue;
            }

            if (parameter.Kind == AbiKind.Shared)
            {
                callParameters.Add(parameter.IsWeakPtr ? "std::weak_ptr<void>" : "std::shared_ptr<void>");
                continue;
            }

            callParameters.Add(parameter.Kind switch
            {
                AbiKind.Opaque when parameter.IsByValueRecord =>
                    ByValueRegisterType(parameter, layouts) ?? "void*",
                AbiKind.Opaque => "void*",
                AbiKind.StringView => parameter.NativeType,
                _ => AbiPlan.CppType(parameter.Kind),
            });
        }

        // An instance member uses RCX for `this` and RDX for the hidden return buffer,
        // while a free function uses RCX for the return buffer and RDX for the first
        // argument. Declare a free-function pointer with (this, result*) to match the
        // member ABI for non-trivial returns.
        var optionalReturnType = SymbolOptionalReturnType(function, layouts);
        var memberStringReturn = function.Kind == AbiFunctionKind.Method
            && !function.Static
            && function.ReturnKind == AbiKind.StringView
            && !function.ReturnOptional
            && !function.NativeReturnType.TrimEnd().EndsWith("&", StringComparison.Ordinal);
        var memberSretReturn = memberStringReturn || largeRecordReturn;

        var callReturn = function.ReturnKind switch
        {
            AbiKind.Void => "void",
            AbiKind.Opaque => "void*",
            AbiKind.StringView => function.NativeReturnType,
            _ => returnType,
        };
        if (function.Kind is AbiFunctionKind.Create or AbiFunctionKind.Destroy || memberSretReturn)
        {
            callReturn = "void";
        }
        else if (smallRecordReturn)
        {
            callReturn = RegisterType(returnLayout!);
        }

        if (arrayReturn)
        {
            callReturn = borrowedVectorReturn ? "void*" : "void";
            yield return $"    using HsVector = std::vector<{vectorElementType}>;";
        }

        // A typed non-trivial return through a free-function pointer would place the return
        // buffer first, which mismatches MSVC member functions. Pass the buffer explicitly and
        // construct/destroy the optional or smart pointer inside it instead. The Itanium ABI
        // puts the buffer first for members as well, and returns small trivially copyable
        // optionals in registers, so Linux uses the typed return.
        var sharedReturnType = function.ReturnKind == AbiKind.Shared
            ? (function.SharedWrapper == SharedWrapperKind.WeakPtr ? "std::weak_ptr<void>" : "std::shared_ptr<void>")
            : null;
        var uniquePtrReturn = function.ReturnUniquePtr;
        var manualOptionalSret = optionalReturnType is not null
            && string.Equals(configuration.Os, "windows", StringComparison.Ordinal);
        var manualTypedSret = manualOptionalSret || sharedReturnType is not null || uniquePtrReturn;
        var typedReturnType = optionalReturnType ?? sharedReturnType
            ?? (uniquePtrReturn ? "std::unique_ptr<void, hs_unique_void_deleter>" : null);
        if (manualTypedSret)
        {
            callReturn = "void";
        }
        else if (optionalReturnType is not null)
        {
            callReturn = optionalReturnType;
        }

        if (memberStringReturn)
        {
            yield return $"    using HsString = {function.NativeReturnType};";
            yield return "    alignas(HsString) unsigned char hs_stringStorage[sizeof(HsString)];";
        }
        else if (largeRecordReturn)
        {
            var align = returnLayout!.Align > 0 ? returnLayout.Align : 8;
            yield return $"    alignas({align.ToString(CultureInfo.InvariantCulture)}) unsigned char hs_recordStorage[{returnLayout.Size.ToString(CultureInfo.InvariantCulture)}];";
        }
        else if (arrayReturn && !borrowedVectorReturn)
        {
            yield return "    alignas(HsVector) unsigned char hs_vectorStorage[sizeof(HsVector)];";
        }
        else if (manualTypedSret)
        {
            yield return $"    using HsTypedResult = {typedReturnType};";
            yield return "    alignas(HsTypedResult) unsigned char hs_typedStorage[sizeof(HsTypedResult)];";
        }

        // MSVC places the hidden return buffer after `this`; the Itanium ABI places it before
        // every explicit argument, including `this`. Static members use the first slot on both.
        var sretIndex = !function.Static && string.Equals(configuration.Os, "windows", StringComparison.Ordinal)
            ? 1
            : 0;
        if (memberStringReturn
            || largeRecordReturn
            || (arrayReturn && !borrowedVectorReturn)
            || manualTypedSret)
        {
            callParameters.Insert(sretIndex, memberStringReturn ? function.NativeReturnType + "*" : "void*");
        }

        yield return $"    using HsFn = {callReturn} (*)({string.Join(", ", callParameters)});";
        if (function.Kind == AbiFunctionKind.Destroy)
        {
            yield return "    auto const hs_fn = reinterpret_cast<HsFn>(hs_dtor);";
            yield return "    if (hs_fn != nullptr) { hs_fn(hs_self); }";
            var align = layout?.Align > 0 ? layout!.Align : 8;
            yield return $"    hs_deallocate(hs_self, {align.ToString(CultureInfo.InvariantCulture)});";
        }
        else
        {
            yield return "    auto const hs_fn = reinterpret_cast<HsFn>(hs_target);";

            if (returnNeedsCopy)
            {
                var (copyOffset, copySymbol) = SymbolFacts(returnCopyConstructor!, configuration.Os);
                var (dtorOffset, dtorSymbol) = SymbolFacts(returnDestructor!, configuration.Os);
                yield return $"    auto const hs_returnCopy = hs_resolve({copyOffset}, {CppLiteral(copySymbol)});";
                yield return $"    auto const hs_returnDtor = hs_resolve({dtorOffset}, {CppLiteral(dtorSymbol)});";
                yield return "    if (hs_returnCopy == nullptr || hs_returnDtor == nullptr)";
                yield return "    {";
                yield return "        setLastError(\"the returned record copy or destructor symbol was not resolved\");";
                yield return "        return nullptr;";
                yield return "    }";
            }

            var callArguments = new List<string>();
            if (function.Kind == AbiFunctionKind.Create)
            {
                callArguments.Add("hs_memory");
            }
            else
            {
                var sretArgument = memberStringReturn
                    ? "reinterpret_cast<HsString*>(hs_stringStorage)"
                    : largeRecordReturn
                        ? "static_cast<void*>(hs_recordStorage)"
                        : arrayReturn && !borrowedVectorReturn
                            ? "static_cast<void*>(hs_vectorStorage)"
                            : manualTypedSret
                                ? "static_cast<void*>(hs_typedStorage)"
                                : null;
                if (sretArgument is not null && sretIndex == 0)
                {
                    callArguments.Add(sretArgument);
                }

                if (!function.Static)
                {
                    callArguments.Add("hs_self");
                }

                if (sretArgument is not null && sretIndex == 1)
                {
                    callArguments.Add(sretArgument);
                }
            }

            for (var index = 0; index < function.Parameters.Count; index++)
            {
                var parameter = function.Parameters[index];
                var name = CppParameterName(parameter, index);
                if (SymbolOptionalType(parameter, layoutsByQualifiedName) is not null)
                {
                    callArguments.Add($"hs_opt{index}");
                    continue;
                }

                if (parameter.Kind == AbiKind.Shared)
                {
                    callArguments.Add(parameter.IsWeakPtr ? $"hs_weak{index}" : $"hs_shared{index}");
                    continue;
                }

                if (parameter.IsVector)
                {
                    callArguments.Add($"static_cast<void*>(&hs_vec{index})");
                    continue;
                }

                callArguments.Add(parameter.Kind switch
                {
                    AbiKind.StringView => $"hs_str{index}",
                    AbiKind.Opaque when parameter.IsByValueRecord => ByValueArgument(parameter, index, layouts),
                    _ => name,
                });
            }

            var call = $"hs_fn({string.Join(", ", callArguments)})";
            if (function.Kind == AbiFunctionKind.Create)
            {
                yield return $"    {call};";
                yield return "    return hs_memory;";
            }
            else if (function.ReturnKind == AbiKind.Void)
            {
                yield return $"    {call};";
            }
            else if (function.ReturnKind == AbiKind.Shared)
            {
                yield return $"    {call};";
                yield return "    auto& hs_shared = *reinterpret_cast<HsTypedResult*>(hs_typedStorage);";
                if (function.SharedWrapper == SharedWrapperKind.WeakPtr)
                {
                    yield return "    auto hs_locked = hs_shared.lock();";
                    yield return "    auto hs_result = hs_make_shared_handle<void>(std::move(hs_locked));";
                }
                else if (function.SharedWrapper == SharedWrapperKind.NonOwnerPtr)
                {
                    yield return "    auto hs_result = hs_make_non_owner_handle<void>(std::move(hs_shared));";
                }
                else
                {
                    yield return "    auto hs_result = hs_make_shared_handle<void>(std::move(hs_shared));";
                }

                yield return "    hs_shared.~HsTypedResult();";
                yield return "    return hs_result;";
            }
            else if (optionalReturnType is not null)
            {
                if (manualOptionalSret)
                {
                    yield return $"    {call};";
                    yield return "    auto& hs_result = *reinterpret_cast<HsTypedResult*>(hs_typedStorage);";
                }
                else
                {
                    yield return $"    auto hs_result = {call};";
                }

                yield return "    *hs_hasValue = hs_result.has_value();";
                if (function.ReturnOptionalRecord)
                {
                    var optionalRecordLayout = layouts[function.ReturnDeclarationId!];
                    var size = optionalRecordLayout.Size.ToString(CultureInfo.InvariantCulture);
                    var align = (optionalRecordLayout.Align > 0 ? optionalRecordLayout.Align : 8).ToString(CultureInfo.InvariantCulture);
                    if (manualOptionalSret)
                    {
                        yield return "    if (!*hs_hasValue) { hs_result.~HsTypedResult(); return nullptr; }";
                    }
                    else
                    {
                        yield return "    if (!*hs_hasValue) { return nullptr; }";
                    }

                    yield return $"    auto* const hs_record = static_cast<void*>(hs_allocate(static_cast<std::size_t>({size}), {align}));";
                    yield return $"    std::memcpy(hs_record, hs_result->data, static_cast<std::size_t>({size}));";
                    if (manualOptionalSret)
                    {
                        yield return "    hs_result.~HsTypedResult();";
                    }

                    yield return "    return hs_record;";
                }
                else if (function.ReturnKind == AbiKind.StringView)
                {
                    yield return "    g_stringResult.assign(hs_result ? hs_result->data() : \"\", hs_result ? hs_result->size() : 0);";
                    if (manualOptionalSret)
                    {
                        yield return "    hs_result.~HsTypedResult();";
                    }

                    yield return "    return HosihikariStringView{g_stringResult.data(), g_stringResult.size()};";
                }
                else
                {
                    yield return $"    auto hs_value = hs_result ? static_cast<{returnType}>(*hs_result) : {returnType}{{}};";
                    if (manualOptionalSret)
                    {
                        yield return "    hs_result.~HsTypedResult();";
                    }

                    yield return "    return hs_value;";
                }
            }
            else if (memberStringReturn)
            {
                yield return $"    {call};";
                yield return "    auto& hs_result = *reinterpret_cast<HsString*>(hs_stringStorage);";
                yield return "    g_stringResult.assign(hs_result.data(), hs_result.size());";
                yield return destroyStringViaGame ? "    hs_destroy_string(&hs_result);" : "    hs_result.~HsString();";
                yield return "    return HosihikariStringView{g_stringResult.data(), g_stringResult.size()};";
            }
            else if (function.ReturnKind == AbiKind.StringView)
            {
                yield return $"    auto hs_result = {call};";
                yield return "    g_stringResult.assign(hs_result.data(), hs_result.size());";
                yield return "    return HosihikariStringView{g_stringResult.data(), g_stringResult.size()};";
            }
            else if (smallRecordReturn)
            {
                yield return $"    auto hs_value = {call};";
                var align = returnLayout!.Align > 0 ? returnLayout.Align : 8;
                yield return $"    auto* const hs_record = static_cast<void*>(hs_allocate(static_cast<std::size_t>({returnLayout.Size.ToString(CultureInfo.InvariantCulture)}), {align.ToString(CultureInfo.InvariantCulture)}));";
                yield return $"    std::memcpy(hs_record, &hs_value, static_cast<std::size_t>({returnLayout.Size.ToString(CultureInfo.InvariantCulture)}));";
                yield return "    return hs_record;";
            }
            else if (arrayReturn)
            {
                if (borrowedVectorReturn)
                {
                    // A reference or pointer result borrows the vector owned by the native side.
                    yield return $"    auto* hs_vectorResult = static_cast<HsVector*>({call});";
                    yield return "    if (hs_vectorResult == nullptr) { return HosihikariArrayView{nullptr, 0}; }";
                }
                else
                {
                    yield return $"    {call};";
                    yield return "    auto* hs_vectorResult = reinterpret_cast<HsVector*>(hs_vectorStorage);";
                }

                if (function.ArrayElementKind == AbiKind.StringView)
                {
                    yield return "    thread_local std::vector<std::string> hs_arrayStrings;";
                    yield return "    thread_local std::vector<HosihikariStringView> hs_arrayViews;";
                    yield return "    hs_arrayStrings.clear();";
                    yield return "    hs_arrayViews.clear();";
                    yield return "    hs_arrayStrings.reserve(hs_vectorResult->size());";
                    yield return "    for (auto const& item : *hs_vectorResult) { hs_arrayStrings.emplace_back(item.data(), item.size()); }";
                    yield return "    hs_arrayViews.reserve(hs_arrayStrings.size());";
                    yield return "    for (auto const& item : hs_arrayStrings) { hs_arrayViews.push_back(HosihikariStringView{item.data(), item.size()}); }";
                    if (!borrowedVectorReturn)
                    {
                        yield return "    hs_vectorResult->~HsVector();";
                    }

                    yield return "    return HosihikariArrayView{hs_arrayViews.data(), hs_arrayViews.size()};";
                }
                else if (function.ArrayElementKind == AbiKind.Opaque)
                {
                    yield return "    thread_local std::vector<void*> hs_arrayResult;";
                    yield return "    hs_arrayResult.clear();";
                    yield return "    hs_arrayResult.reserve(hs_vectorResult->size());";
                    if (function.ArrayElementOwnership == ArrayElementOwnership.None)
                    {
                        yield return "    for (auto const& item : *hs_vectorResult) { hs_arrayResult.push_back(const_cast<void*>(static_cast<void const*>(item))); }";
                    }
                    else
                    {
                        var size = vectorElementLayout!.Size.ToString(CultureInfo.InvariantCulture);
                        var align = (vectorElementLayout.Align > 0 ? vectorElementLayout.Align : 8)
                            .ToString(CultureInfo.InvariantCulture);
                        yield return "    for (auto const& item : *hs_vectorResult)";
                        yield return "    {";
                        yield return $"        auto* const hs_copy = static_cast<void*>(hs_allocate(static_cast<std::size_t>({size}), {align}));";
                        yield return $"        std::memcpy(hs_copy, item.data, static_cast<std::size_t>({size}));";
                        yield return "        hs_arrayResult.push_back(hs_copy);";
                        yield return "    }";
                    }

                    if (!borrowedVectorReturn)
                    {
                        yield return "    hs_vectorResult->~HsVector();";
                    }

                    yield return "    return HosihikariArrayView{hs_arrayResult.data(), hs_arrayResult.size()};";
                }
                else
                {
                    var elementType = AbiPlan.CppType(function.ArrayElementKind);
                    yield return $"    thread_local std::vector<{elementType}> hs_arrayResult;";
                    yield return "    hs_arrayResult.clear();";
                    yield return "    hs_arrayResult.reserve(hs_vectorResult->size());";
                    yield return $"    for (auto const& item : *hs_vectorResult) {{ hs_arrayResult.push_back(static_cast<{elementType}>(item)); }}";
                    if (!borrowedVectorReturn)
                    {
                        yield return "    hs_vectorResult->~HsVector();";
                    }

                    yield return "    return HosihikariArrayView{hs_arrayResult.data(), hs_arrayResult.size()};";
                }
            }
            else if (function.ReturnUniquePtr)
            {
                yield return $"    {call};";
                yield return "    auto& hs_unique = *reinterpret_cast<HsTypedResult*>(hs_typedStorage);";
                yield return "    void* hs_result = hs_unique.release();";
                yield return "    hs_unique.~HsTypedResult();";
                yield return "    return hs_result;";
            }
            else if (ownedRecordReturn)
            {
                yield return $"    {call};";
                var align = returnLayout!.Align > 0 ? returnLayout.Align : 8;
                yield return $"    auto* const hs_record = static_cast<void*>(hs_allocate(static_cast<std::size_t>({returnLayout.Size.ToString(CultureInfo.InvariantCulture)}), {align.ToString(CultureInfo.InvariantCulture)}));";
                if (returnNeedsCopy)
                {
                    yield return "    using HsCopy = void (*)(void*, void*);";
                    yield return "    using HsReturnDtor = void (*)(void*);";
                    yield return "    reinterpret_cast<HsCopy>(hs_returnCopy)(hs_record, hs_recordStorage);";
                    yield return "    reinterpret_cast<HsReturnDtor>(hs_returnDtor)(hs_recordStorage);";
                }
                else
                {
                    yield return $"    std::memcpy(hs_record, hs_recordStorage, static_cast<std::size_t>({returnLayout.Size.ToString(CultureInfo.InvariantCulture)}));";
                }

                yield return "    return hs_record;";
            }
            else if (function.ReturnKind == AbiKind.Opaque)
            {
                if (function.ReturnOptional)
                {
                    yield return $"    auto hs_result = {call};";
                    yield return "    *hs_hasValue = hs_result != nullptr;";
                    yield return "    return hs_result;";
                }
                else
                {
                    yield return $"    return {call};";
                }
            }
            else
            {
                yield return $"    return static_cast<{returnType}>({call});";
            }
        }

        foreach (var line in SymbolCatchTail(function.ReturnKind))
        {
            yield return line;
        }
    }

    private static IEnumerable<string> SymbolCatchTail(AbiKind returnKind)
    {
        yield return "}";
        yield return "catch (std::exception const& hs_error)";
        yield return "{";
        yield return "    setLastError(hs_error.what());";
        yield return "    " + DefaultReturn(returnKind);
        yield return "}";
        yield return "catch (...)";
        yield return "{";
        yield return "    setLastError(\"unknown native exception\");";
        yield return "    " + DefaultReturn(returnKind);
        yield return "}";
    }

    private static string RegisterType(LayoutInfo layout) => layout.Size switch
    {
        1 => "std::uint8_t",
        2 => "std::uint16_t",
        4 => "std::uint32_t",
        8 => "std::uint64_t",
        _ => "void*",
    };

    private static LayoutInfo? ByValueLayout(
        AbiParameter parameter,
        IReadOnlyDictionary<string, LayoutInfo> layouts) =>
        parameter.ByValueDeclarationId is not null
        && layouts.TryGetValue(parameter.ByValueDeclarationId, out var layout)
            ? layout
            : null;

    private static string? ByValueRegisterType(
        AbiParameter parameter,
        IReadOnlyDictionary<string, LayoutInfo> layouts) =>
        // A user-provided copy constructor makes the record non-trivial for calls, so the
        // MSVC and Itanium ABIs pass it by hidden reference even when it is small.
        parameter.ByValueTriviallyCopyable
            ? ByValueLayout(parameter, layouts)?.Size switch
            {
                1 => "std::uint8_t",
                2 => "std::uint16_t",
                4 => "std::uint32_t",
                8 => "std::uint64_t",
                _ => null,
            }
            : null;

    private static string ByValueArgument(
        AbiParameter parameter,
        int index,
        IReadOnlyDictionary<string, LayoutInfo> layouts)
    {
        var layout = ByValueLayout(parameter, layouts);
        var registerType = ByValueRegisterType(parameter, layouts);
        return layout is { Size: <= 8 } && registerType is not null
            ? $"*reinterpret_cast<{registerType} const*>({CppParameterName(parameter, index)})"
            : $"hs_arg{index}Storage";
    }

    private static bool HasDispatchSymbol(MemberRecord member) =>
        !string.IsNullOrWhiteSpace(member.Symbol)
        || member.Address is not null
        || member.Rva is not null;

    private static bool IsCopyConstructorRecord(MemberRecord member, string typeName)
    {
        if (member.Signature is null || member.Signature.Parameters.Count != 1)
        {
            return false;
        }

        var type = member.Signature.Parameters[0].Type.Trim();
        while (type.EndsWith("&", StringComparison.Ordinal))
        {
            type = type[..^1].TrimEnd();
        }

        type = type
            .Replace("const ", "", StringComparison.Ordinal)
            .Replace(" const", "", StringComparison.Ordinal)
            .Replace("volatile ", "", StringComparison.Ordinal)
            .Replace(" volatile", "", StringComparison.Ordinal)
            .Trim();
        return string.Equals(type, typeName.Trim(), StringComparison.Ordinal);
    }

    private static (string Offset, string Symbol)? StringDestructor(IrManifest manifest, IrConfiguration configuration)
    {
        if (!manifest.SupportSymbols.TryGetValue("stdStringDestructor", out var symbols)
            || !symbols.TryGetValue(configuration.Id, out var symbol))
        {
            return null;
        }

        var offset = string.Equals(configuration.Os, "windows", StringComparison.Ordinal)
            ? symbol.Rva
            : symbol.Address;
        if (offset is not > 0 || string.IsNullOrWhiteSpace(symbol.Symbol))
        {
            return null;
        }

        return ("std::uintptr_t{" + offset.Value.ToString(CultureInfo.InvariantCulture) + "}", symbol.Symbol);
    }

    private static (string Offset, string Symbol) SymbolFacts(MemberRecord member, string os)
    {
        ulong? offset = string.Equals(os, "windows", StringComparison.Ordinal)
            ? member.Rva
            : member.Address;
        var value = offset is > 0 ? offset.Value : 0UL;
        var offsetText = "std::uintptr_t{" + value.ToString(CultureInfo.InvariantCulture) + "}";
        return (offsetText, member.Symbol ?? "");
    }

    private static string CppLiteral(string value) => "\"" + EscapeCpp(value) + "\"";

    private static string EscapeCpp(string value) => value
        .Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal);
}
