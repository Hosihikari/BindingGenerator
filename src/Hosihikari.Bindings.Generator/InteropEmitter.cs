using System.Text;
using Hosihikari.Bindings.Ir;

namespace Hosihikari.Bindings.Generator;

internal static class InteropEmitter
{
    private const string StubReason = "BindingShim is not wired yet.";

    public static void Emit(IReadOnlyList<IrRecord> records, string outputDirectory)
    {
        var declarations = records.OfType<DeclarationRecord>()
            .OrderBy(declaration => declaration.Id, StringComparer.Ordinal)
            .ToList();

        var members = records.OfType<MemberRecord>()
            .GroupBy(member => member.DeclarationId, StringComparer.Ordinal)
            .ToDictionary(
                group => group.Key,
                group => group.GroupBy(member => member.Id, StringComparer.Ordinal)
                    .Select(byId => byId.First())
                    .OrderBy(member => member.Id, StringComparer.Ordinal)
                    .ToList(),
                StringComparer.Ordinal);

        foreach (var declaration in declarations)
        {
            if (declaration.Kind is not ("class" or "struct" or "union"))
            {
                continue;
            }

            var nativeNamespace = TypeNames.NativeNamespace(declaration.QualifiedName);
            var namespaceName = $"Hosihikari.Bindings.{TypeNames.SurfaceNamespace(declaration.Surface)}.Interop";
            if (nativeNamespace.Length > 0)
            {
                var escapedSegments = nativeNamespace
                    .Split('.', StringSplitOptions.RemoveEmptyEntries)
                    .Select(TypeNames.Escape);
                namespaceName += "." + string.Join(".", escapedSegments);
            }

            var className = TypeNames.Escape(TypeNames.NativeName(declaration.QualifiedName));
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "",
                $"namespace {namespaceName};",
                "",
                $"public sealed partial class {className}",
                "{",
                "    private readonly nint _handle;",
                "",
                $"    public {className}(nint handle) => _handle = handle;",
                "",
                "    public nint Handle => _handle;",
            };

            if (members.TryGetValue(declaration.Id, out var declarationMembers))
            {
                foreach (var member in declarationMembers)
                {
                    if (member.Access == "private")
                    {
                        continue;
                    }

                    lines.Add("");
                    EmitMember(lines, member);
                }
            }

            lines.Add("}");

            var relative = Path.Combine(
                "interop",
                declaration.Surface,
                nativeNamespace.Replace('.', Path.DirectorySeparatorChar),
                className + ".g.cs");
            var path = Path.Combine(outputDirectory, relative);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static void EmitMember(List<string> lines, MemberRecord member)
    {
        var name = TypeNames.Escape(member.Name);
        switch (member.Kind)
        {
            case "field":
            case "static_field":
            {
                var type = TypeNames.ToCSharpType(member.Type);
                var modifier = member.Static ? "static " : "";
                lines.Add($"    public {modifier}{type} {name}");
                lines.Add("    {");
                lines.Add($"        get => throw new global::System.NotSupportedException(\"{StubReason}\");");
                lines.Add($"        set => throw new global::System.NotSupportedException(\"{StubReason}\");");
                lines.Add("    }");
                break;
            }

            case "method":
            case "function":
            case "operator":
            {
                var returnCanonical = member.Signature?.ReturnType ?? member.Type?.Canonical ?? "void";
                var returnType = TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = returnCanonical });
                var parameters = member.Signature is null
                    ? ""
                    : string.Join(
                        ", ",
                        member.Signature.Parameters.Select((parameter, index) =>
                            $"{TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = parameter.Type })} {TypeNames.Escape(string.IsNullOrWhiteSpace(parameter.Name) ? $"arg{index}" : parameter.Name)}"));
                var modifier = member.Static ? "static " : "";
                lines.Add($"    public {modifier}{returnType} {name}({parameters}) =>");
                lines.Add($"        throw new global::System.NotSupportedException(\"{StubReason}\");");
                break;
            }

            default:
                lines.Add($"    // member kind '{member.Kind}' is not emitted by the stub");
                break;
        }
    }
}
