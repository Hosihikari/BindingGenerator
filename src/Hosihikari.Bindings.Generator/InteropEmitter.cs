using System.Text;
using Hosihikari.Bindings.Ir;

namespace Hosihikari.Bindings.Generator;

internal static class InteropEmitter
{
    private const string StubReason = "BindingShim is not wired yet.";

    public static void Emit(IReadOnlyList<IrRecord> records, string outputDirectory)
    {
        var declarations = records.OfType<DeclarationRecord>()
            .Where(declaration => (declaration.Kind is "class" or "struct" or "union")
                && !declaration.QualifiedName.Contains('<')
                && !declaration.QualifiedName.Contains('>'))
            .OrderBy(declaration => declaration.Id, StringComparer.Ordinal)
            .ToList();

        var members = records.OfType<MemberRecord>()
            .GroupBy(member => member.DeclarationId, StringComparer.Ordinal)
            .ToDictionary(
                group => group.Key,
                group => group.GroupBy(member => member.Id, StringComparer.Ordinal)
                    .Select(byId => byId.First())
                    .OrderBy(member => member.Id, StringComparer.Ordinal)
                    .ToList(),
                StringComparer.Ordinal);

        var declarationNames = BuildDeclarationNames(declarations);

        foreach (var declaration in declarations)
        {
            var name = declarationNames[declaration.Id];
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "",
                $"namespace {name.NamespaceName};",
                "",
                $"public sealed partial class {name.ClassName}",
                "{",
                "    private readonly nint _handle;",
                "",
                $"    public {name.ClassName}(nint handle) => _handle = handle;",
                "",
                "    public nint Handle => _handle;",
            };

            if (members.TryGetValue(declaration.Id, out var declarationMembers))
            {
                var memberNames = BuildMemberNames(declarationMembers);
                foreach (var member in declarationMembers)
                {
                    if (member.Access == "private")
                    {
                        continue;
                    }

                    lines.Add("");
                    EmitMember(lines, member, memberNames[member.Id]);
                }
            }

            lines.Add("}");

            var pathSegments = new List<string> { "interop", declaration.Surface };
            if (name.NamespacePath.Length > 0)
            {
                pathSegments.AddRange(name.NamespacePath.Split('.', StringSplitOptions.RemoveEmptyEntries));
            }

            pathSegments.Add(name.ClassName + ".g.cs");
            var path = Path.Combine(outputDirectory, Path.Combine(pathSegments.ToArray()));
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static Dictionary<string, DeclarationName> BuildDeclarationNames(IReadOnlyList<DeclarationRecord> declarations)
    {
        var classNames = declarations
            .Select(declaration => declaration.QualifiedName)
            .ToHashSet(StringComparer.Ordinal);

        var result = new Dictionary<string, DeclarationName>(StringComparer.Ordinal);
        var candidates = declarations
            .Select(declaration =>
            {
                var (namespaceName, namespacePath) = BuildNamespace(declaration, classNames);
                return (
                    Declaration: declaration,
                    NamespaceName: namespaceName,
                    NamespacePath: namespacePath,
                    Class: TypeNames.Sanitize(TypeNames.NativeName(declaration.QualifiedName)));
            })
            .ToList();

        foreach (var group in candidates.GroupBy(candidate => (candidate.NamespaceName, candidate.Class)))
        {
            var duplicate = group.Count() > 1;
            foreach (var candidate in group)
            {
                var className = duplicate
                    ? candidate.Class + "_" + ShortHash(candidate.Declaration.Id)
                    : candidate.Class;
                result[candidate.Declaration.Id] = new DeclarationName(
                    candidate.NamespaceName,
                    candidate.NamespacePath,
                    className);
            }
        }

        return result;
    }

    private static (string NamespaceName, string NamespacePath) BuildNamespace(
        DeclarationRecord declaration,
        HashSet<string> classNames)
    {
        var parts = declaration.QualifiedName.Split("::", StringSplitOptions.RemoveEmptyEntries);
        var segments = new List<string>();
        var nativePrefix = "";
        var parentCount = Math.Max(0, parts.Length - 1);
        for (var index = 0; index < parentCount; index++)
        {
            var part = parts[index];
            nativePrefix = nativePrefix.Length == 0 ? part : nativePrefix + "::" + part;
            var segment = TypeNames.Sanitize(part);
            if (classNames.Contains(nativePrefix))
            {
                segment += "_Nested";
            }

            segments.Add(segment);
        }

        var baseName = $"Hosihikari.Bindings.{TypeNames.SurfaceNamespace(declaration.Surface)}.Interop";
        var namespaceName = segments.Count == 0 ? baseName : baseName + "." + string.Join(".", segments);
        return (namespaceName, string.Join(".", segments));
    }

    private static Dictionary<string, string> BuildMemberNames(IReadOnlyList<MemberRecord> members)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        var candidates = members
            .Select(member => (
                Member: member,
                Name: TypeNames.Sanitize(member.Name),
                Key: MemberKey(member)))
            .ToList();

        foreach (var group in candidates.GroupBy(candidate => (candidate.Name, candidate.Key)))
        {
            var duplicate = group.Count() > 1;
            foreach (var candidate in group)
            {
                var name = duplicate
                    ? candidate.Name + "_" + ShortHash(candidate.Member.Id)
                    : candidate.Name;
                result[candidate.Member.Id] = name;
            }
        }

        return result;
    }

    private static string MemberKey(MemberRecord member)
    {
        if (member.Kind is "method" or "function" or "operator")
        {
            var parameters = member.Signature?.Parameters
                .Select(parameter => TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = parameter.Type }))
                ?? [];
            return "method:" + string.Join(",", parameters);
        }

        return "field";
    }

    private static string ShortHash(string value) => IrHash.Sha256Hex(value).Substring(0, 8);

    private static void EmitMember(List<string> lines, MemberRecord member, string name)
    {
        switch (member.Kind)
        {
            case "field":
            case "static_field":
            {
                var type = TypeNames.ToCSharpType(member.Type);
                var modifier = member.Static ? "static " : "";
                lines.Add($"    public {modifier}{type} {name}");
                lines.Add("    {");
                lines.Add($"        get => throw new global::System.NotSupportedException(\"{StubReason}\");");
                lines.Add($"        set => throw new global::System.NotSupportedException(\"{StubReason}\");");
                lines.Add("    }");
                break;
            }

            case "method":
            case "function":
            case "operator":
            {
                var returnCanonical = member.Signature?.ReturnType ?? member.Type?.Canonical ?? "void";
                var returnType = TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = returnCanonical });
                var parameters = member.Signature is null
                    ? ""
                    : string.Join(
                        ", ",
                        member.Signature.Parameters.Select((parameter, index) =>
                            $"{TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = parameter.Type })} {TypeNames.Sanitize(string.IsNullOrWhiteSpace(parameter.Name) ? $"arg{index}" : parameter.Name)}"));
                var modifier = member.Static ? "static " : "";
                lines.Add($"    public {modifier}{returnType} {name}({parameters}) =>");
                lines.Add($"        throw new global::System.NotSupportedException(\"{StubReason}\");");
                break;
            }

            default:
                lines.Add($"    // member kind '{member.Kind}' is not emitted by the stub");
                break;
        }
    }

    private readonly record struct DeclarationName(string NamespaceName, string NamespacePath, string ClassName);
}
