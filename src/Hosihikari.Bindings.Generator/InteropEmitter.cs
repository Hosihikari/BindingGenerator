using System.Text;
using Hosihikari.Bindings.Ir;

namespace Hosihikari.Bindings.Generator;

internal static class InteropEmitter
{
    private const string DefaultStubReason = "BindingShim does not expose this member.";

    private static string StubMessage(AbiPlan plan, MemberRecord member) =>
        plan.TryGetSkipReason(member.Id, out var reason)
            ? $"BindingShim cannot project this member: {reason}."
            : DefaultStubReason;

    public static void Emit(IReadOnlyList<IrRecord> records, string outputDirectory, AbiPlan plan)
    {
        var declarations = records.OfType<DeclarationRecord>()
            .Where(declaration => declaration.Kind is "class" or "struct" or "union")
            .Where(declaration => declaration.Access == "public")
            .OrderBy(declaration => declaration.Id, StringComparer.Ordinal)
            .ToList();

        var members = records.OfType<MemberRecord>()
            .GroupBy(member => member.DeclarationId, StringComparer.Ordinal)
            .ToDictionary(
                group => group.Key,
                group => group.GroupBy(member => member.Id, StringComparer.Ordinal)
                    .Select(byId => byId.First())
                    .OrderBy(member => member.Id, StringComparer.Ordinal)
                    .ToList(),
                StringComparer.Ordinal);

        var declarationNames = CSharpNaming.BuildDeclarationNames(declarations);

        EmitNativeMethods(outputDirectory, plan);

        foreach (var declaration in declarations)
        {
            var name = declarationNames[declaration.Id];
            var hasDestroy = plan.DestroyByDeclaration.TryGetValue(declaration.Id, out var destroy);
            var hasRealFunction = plan.FunctionsByDeclaration.ContainsKey(declaration.Id);
            var classModifier = hasRealFunction ? "unsafe " : "";
            var interfaceClause = hasDestroy ? " : global::System.IDisposable" : "";
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "",
                $"namespace {name.NamespaceName};",
                "",
                $"public sealed {classModifier}partial class {name.ClassName}{interfaceClause}",
                "{",
                "    private nint _handle;",
                "",
                $"    public {name.ClassName}(nint handle) => _handle = handle;",
                "",
                "    public nint Handle => _handle;",
            };

            if (members.TryGetValue(declaration.Id, out var declarationMembers))
            {
                var memberNames = BuildMemberNames(declarationMembers, plan);
                foreach (var member in declarationMembers)
                {
                    if (member.Access != "public")
                    {
                        continue;
                    }

                    lines.Add("");
                    EmitMember(lines, member, memberNames[member.Id], name.ClassName, plan, hasDestroy);
                }
            }

            if (hasDestroy)
            {
                lines.Add("");
                EmitDispose(lines, destroy!);
            }

            lines.Add("}");

            var fileName = name.ClassName + "_" + CSharpNaming.ShortHash(declaration.Id) + ".g.cs";
            var path = Path.Combine(outputDirectory, "interop", declaration.Surface, fileName);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static void EmitNativeMethods(string outputDirectory, AbiPlan plan)
    {
        foreach (var surface in plan.Functions
                     .Select(function => function.Surface)
                     .Distinct(StringComparer.Ordinal)
                     .OrderBy(surface => surface, StringComparer.Ordinal))
        {
            var functions = plan.FunctionsForSurface(surface)
                .OrderBy(function => function.Index)
                .ToList();
            if (functions.Count == 0)
            {
                continue;
            }

            var namespaceName = $"Hosihikari.Bindings.{TypeNames.SurfaceNamespace(surface)}.Interop";
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "using System.Runtime.CompilerServices;",
                "",
                $"namespace {namespaceName};",
                "",
                "public static unsafe class NativeMethods",
                "{",
                "    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential)]",
                "    internal struct StringView",
                "    {",
                "        public byte* Data;",
                "        public nuint Size;",
                "    }",
                "",
                "    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential)]",
                "    internal struct ArrayView",
                "    {",
                "        public void* Data;",
                "        public nuint Size;",
                "    }",
                "",
                "    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential)]",
                "    internal struct SharedHandle",
                "    {",
                "        public void* Holder;",
                "        public void* Target;",
                "        public delegate* unmanaged[Cdecl]<void*, void> Release;",
                "    }",
                "",
                "    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential)]",
                "    internal struct Table",
                "    {",
                "        public uint Version;",
                "        public uint Size;",
            };

            foreach (var function in functions)
            {
                lines.Add($"        public {CSharpFunctionPointerType(function)} {function.TableField};");
            }

            lines.AddRange(
            [
                "    }",
                "",
                "    private static Table* s_table;",
                "    private static delegate* unmanaged[Cdecl]<byte*> s_getLastError;",
                "",
                "    public static string? GetLastError()",
                "    {",
                "        if (s_getLastError == null)",
                "        {",
                "            return null;",
                "        }",
                "",
                "        var pointer = s_getLastError();",
                "        return pointer == null ? null : global::System.Runtime.InteropServices.Marshal.PtrToStringUTF8((nint)pointer);",
                "    }",
                "",
                "    internal static Table* TablePtr",
                "    {",
                "        get",
                "        {",
                "            if (s_table == null)",
                "            {",
                "                throw new global::System.InvalidOperationException(\"BindingShim is not loaded. Call NativeMethods.Load(path) first.\");",
                "            }",
                "",
                "            return s_table;",
                "        }",
                "    }",
                "",
                "    public static void Load(string nativeLibraryPath)",
                "    {",
                "        var library = global::System.Runtime.InteropServices.NativeLibrary.Load(nativeLibraryPath);",
                "        var export = global::System.Runtime.InteropServices.NativeLibrary.GetExport(library, \"hosihikari_get_binding_table_v1\");",
                "        var errorExport = global::System.Runtime.InteropServices.NativeLibrary.GetExport(library, \"hosihikari_get_last_error\");",
                "        s_getLastError = (delegate* unmanaged[Cdecl]<byte*>)errorExport.ToPointer();",
                "        var getTable = (delegate* unmanaged[Cdecl]<Table*>)export.ToPointer();",
                "        var table = getTable();",
                "        if (table->Version != 1)",
                "        {",
                "            throw new global::System.InvalidOperationException($\"Unsupported BindingShim table version {table->Version}.\");",
                "        }",
                "",
                "        if (table->Size != (uint)sizeof(Table))",
                "        {",
                "            throw new global::System.InvalidOperationException($\"BindingShim table size mismatch: native {table->Size}, managed {sizeof(Table)}.\");",
                "        }",
                "",
                "        s_table = table;",
                "    }",
                "}",
            ]);

            if (string.Equals(surface, "endstone", StringComparison.Ordinal))
            {
                var loadIndex = lines.FindIndex(line => line.Trim() == "s_table = table;");
                if (loadIndex >= 0)
                {
                    lines.Insert(
                        loadIndex,
                        "        s_getServer = (delegate* unmanaged[Cdecl]<void*>)global::System.Runtime.InteropServices.NativeLibrary.GetExport(library, \"hosihikari_endstone_get_server\").ToPointer();");
                }

                lines.InsertRange(lines.Count - 1,
                [
                    "    private static delegate* unmanaged[Cdecl]<void*> s_getServer;",
                    "",
                    "    public static nint GetServer()",
                    "    {",
                    "        if (s_getServer == null)",
                    "        {",
                    "            throw new global::System.InvalidOperationException(\"BindingShim is not loaded. Call NativeMethods.Load(path) first.\");",
                    "        }",
                    "",
                    "        var server = s_getServer();",
                    "        if (server == null)",
                    "        {",
                    "            throw new global::System.InvalidOperationException(GetLastError() ?? \"Failed to get the Endstone server.\");",
                    "        }",
                    "",
                    "        return (nint)server;",
                    "    }",
                    "",
                ]);
            }

            var path = Path.Combine(outputDirectory, "interop", surface, "NativeMethods.g.cs");
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));

            var sharedLines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "",
                $"namespace {namespaceName};",
                "",
                "public sealed unsafe class SharedHandle : global::System.IDisposable",
                "{",
                "    private nint _holder;",
                "    private delegate* unmanaged[Cdecl]<void*, void> _release;",
                "",
                "    internal SharedHandle(nint holder, nint target, delegate* unmanaged[Cdecl]<void*, void> release)",
                "    {",
                "        _holder = holder;",
                "        _release = release;",
                "        Target = target;",
                "    }",
                "",
                "    public nint Target { get; }",
                "",
                "    public nint Handle => Target;",
                "",
                "    public bool IsDisposed => _holder == 0;",
                "",
                "    public void Dispose()",
                "    {",
                "        if (_holder != 0)",
                "        {",
                "            _release((void*)_holder);",
                "            _holder = 0;",
                "        }",
                "    }",
                "}",
            };
            File.WriteAllText(
                Path.Combine(outputDirectory, "interop", surface, "SharedHandle.g.cs"),
                string.Join("\n", sharedLines) + "\n",
                new UTF8Encoding(false));
        }
    }

    private static string CSharpFunctionPointerType(AbiFunction function)
    {
        var types = new List<string>();
        if (function.Kind != AbiFunctionKind.Create && !function.Static)
        {
            types.Add("void*");
        }

        foreach (var parameter in function.Parameters)
        {
            if (parameter.IsVector)
            {
                continue;
            }

            switch (parameter.Kind)
            {
                case AbiKind.StringView:
                    types.Add("byte*");
                    types.Add("nuint");
                    break;
                case AbiKind.Opaque:
                    types.Add("void*");
                    break;
                case AbiKind.Callback:
                    types.Add("void*");
                    types.Add("void*");
                    types.Add("void*");
                    break;
                default:
                    types.Add(AbiPlan.CSharpType(parameter.Kind));
                    break;
            }
        }

        foreach (var parameter in function.Parameters.Where(parameter => parameter.IsVector))
        {
            types.Add(parameter.VectorElementKind == AbiKind.StringView
                ? "NativeMethods.StringView*"
                : AbiPlan.CSharpType(parameter.VectorElementKind) + "*");
            types.Add("nuint");
        }

        foreach (var parameter in function.Parameters.Where(parameter => parameter.IsOptional))
        {
            types.Add("bool");
        }

        if (function.NeedsPresenceFlag)
        {
            types.Add("bool*");
        }

        types.Add(AbiPlan.CSharpTableType(function.ReturnKind));
        return "delegate* unmanaged[Cdecl]<" + string.Join(", ", types) + ">";
    }

    private static Dictionary<string, string> BuildMemberNames(IReadOnlyList<MemberRecord> members, AbiPlan plan)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        var candidates = members
            .Select(member => (
                Member: member,
                Name: MemberBaseName(member),
                Key: MemberKey(member, plan)))
            .ToList();

        foreach (var group in candidates.GroupBy(candidate => (candidate.Name, candidate.Key)))
        {
            var duplicate = group.Count() > 1;
            foreach (var candidate in group)
            {
                var name = duplicate
                    ? candidate.Name + "_" + CSharpNaming.ShortHash(candidate.Member.Id)
                    : candidate.Name;
                result[candidate.Member.Id] = name;
            }
        }

        return result;
    }

    private static string MemberKey(MemberRecord member, AbiPlan plan)
    {
        if (member.Kind == "constructor" && plan.CreateByMember.TryGetValue(member.Id, out var create))
        {
            return "constructor:" + string.Join(",", create.Parameters.Select(ParameterKey));
        }

        if (member.Kind is "method" or "operator"
            && plan.MethodByMember.TryGetValue(member.Id, out var method))
        {
            return member.Kind + ":" + string.Join(",", method.Parameters.Select(ParameterKey));
        }

        if (member.Kind is "method" or "function" or "operator" or "constructor" or "destructor")
        {
            var parameters = member.Signature?.Parameters
                .Select(parameter => TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = parameter.Type }))
                ?? [];
            return member.Kind + ":" + string.Join(",", parameters);
        }

        return "field";
    }

    private static string ParameterKey(AbiParameter parameter) =>
        parameter.IsVector
            ? "vector:" + parameter.VectorElementType
            : parameter.IsOptionalRef
                ? "optional_ref:" + parameter.OptionalRefInnerType
                : parameter.IsOptional
                    ? "optional:" + parameter.OptionalInnerType
                    : parameter.Kind == AbiKind.Callback
                    ? "callback:" + parameter.Callback!.NativeType
                    : AbiPlan.CSharpParameterType(parameter);

    private static string MemberBaseName(MemberRecord member) => member.Kind switch
    {
        "constructor" => "Create",
        "destructor" => "Destroy",
        "operator" => OperatorName(member),
        _ => TypeNames.Sanitize(member.Name),
    };

    private static string OperatorName(MemberRecord member)
    {
        return member.Name switch
        {
            "operator==" => "operator_equal",
            "operator!=" => "operator_not_equal",
            "operator<" => "operator_less",
            "operator<=" => "operator_less_equal",
            "operator>" => "operator_greater",
            "operator>=" => "operator_greater_equal",
            "operator<=>" => "operator_compare",
            "operator+" => "operator_add",
            "operator-" => "operator_subtract",
            "operator*" => "operator_multiply",
            "operator/" => "operator_divide",
            "operator%" => "operator_modulo",
            "operator[]" => "operator_index",
            "operator()" => "operator_call",
            "operator=" => "operator_assign",
            _ => BuildConversionOperatorName(member),
        };
    }

    private static string BuildConversionOperatorName(MemberRecord member)
    {
        var target = member.Name.StartsWith("operator ", StringComparison.Ordinal)
            ? member.Name["operator ".Length..]
            : member.Name;
        var name = TypeNames.Sanitize(target).TrimStart('@');
        if (name.Length > 60)
        {
            name = name[..60] + "_" + CSharpNaming.ShortHash(member.Id);
        }

        return "operator_" + name;
    }

    private static void EmitMember(
        List<string> lines,
        MemberRecord member,
        string name,
        string className,
        AbiPlan plan,
        bool hasDestroy)
    {
        var stubMessage = StubMessage(plan, member);
        switch (member.Kind)
        {
            case "field":
            case "static_field":
                EmitField(lines, member, name, plan, stubMessage);
                break;

            case "constructor":
                if (plan.CreateByMember.TryGetValue(member.Id, out var create))
                {
                    EmitCreate(lines, className, name, create);
                }
                else
                {
                    lines.Add($"    public static {className} {name}({CSharpParameters(member)}) =>");
                    lines.Add($"        throw new global::System.NotSupportedException(\"{stubMessage}\");");
                }

                break;

            case "destructor":
                if (!hasDestroy)
                {
                    lines.Add($"    public void {name}() =>");
                    lines.Add($"        throw new global::System.NotSupportedException(\"{stubMessage}\");");
                }

                break;

            case "method":
            case "operator":
                if (plan.MethodByMember.TryGetValue(member.Id, out var method))
                {
                    EmitMethod(lines, name, method);
                }
                else
                {
                    EmitMethodStub(lines, member, name, stubMessage);
                }

                break;

            case "function":
                EmitMethodStub(lines, member, name, stubMessage);
                break;

            default:
                lines.Add($"    // member kind '{member.Kind}' is not emitted by the stub");
                break;
        }
    }

    private static void EmitField(
        List<string> lines,
        MemberRecord member,
        string name,
        AbiPlan plan,
        string stubMessage)
    {
        var hasGetter = plan.GetByMember.TryGetValue(member.Id, out var getter);
        var hasSetter = plan.SetByMember.TryGetValue(member.Id, out var setter);
        var modifier = member.Static ? "static " : "";
        if (!hasGetter && !hasSetter)
        {
            var type = TypeNames.ToCSharpType(member.Type);
            lines.Add($"    public {modifier}{type} {name}");
            lines.Add("    {");
            lines.Add($"        get => throw new global::System.NotSupportedException(\"{stubMessage}\");");
            lines.Add($"        set => throw new global::System.NotSupportedException(\"{stubMessage}\");");
            lines.Add("    }");
            return;
        }

        var propertyType = AbiPlan.CSharpPropertyType((getter ?? setter!).ReturnKind);
        lines.Add($"    public {modifier}{propertyType} {name}");
        lines.Add("    {");
        if (hasGetter)
        {
            var self = getter!.Static ? "" : "(void*)_handle";
            var call = $"NativeMethods.TablePtr->{getter.TableField}({self})";
            switch (getter.ReturnKind)
            {
                case AbiKind.StringView:
                    lines.Add("        get");
                    lines.Add("        {");
                    lines.Add($"            var view = {call};");
                    lines.Add("            return global::System.Text.Encoding.UTF8.GetString(view.Data, checked((int)view.Size));");
                    lines.Add("        }");
                    break;
                case AbiKind.Opaque:
                    lines.Add($"        get => (nint){call};");
                    break;
                default:
                    lines.Add($"        get => {call};");
                    break;
            }
        }

        if (hasSetter)
        {
            var arguments = setter!.Static ? "value" : "(void*)_handle, value";
            if (setter.Parameters.Count > 0 && setter.Parameters[0].Kind == AbiKind.Opaque)
            {
                arguments = setter.Static ? "(void*)value" : "(void*)_handle, (void*)value";
            }

            lines.Add($"        set => NativeMethods.TablePtr->{setter.TableField}({arguments});");
        }

        lines.Add("    }");
    }

    private static void EmitCreate(List<string> lines, string className, string name, AbiFunction create)
    {
        var declarations = ParameterDeclarations(create.Parameters);
        var stringIndex = FindStringParameter(create.Parameters);
        var stringName = stringIndex >= 0
            ? CSharpParameterName(create.Parameters[stringIndex], stringIndex)
            : null;
        var arguments = string.Join(
            ", ",
            BuildCallArgumentList(create.Parameters, stringIndex >= 0 ? "__hs_stringData" : null));
        lines.Add($"    public static {className} {name}({declarations})");
        lines.Add("    {");
        EmitPinnedBody(
            lines,
            create.Parameters,
            stringIndex,
            stringName,
            FindVectorParameter(create.Parameters),
            "        ",
            bodyIndent =>
            {
                lines.Add(bodyIndent + $"var handle = NativeMethods.TablePtr->{create.TableField}({arguments});");
                EmitHandleCheck(lines, bodyIndent);
                lines.Add(bodyIndent + $"return new {className}((nint)handle);");
            });
        lines.Add("    }");
    }

    private static void EmitHandleCheck(List<string> lines, string indent = "        ")
    {
        lines.Add(indent + "if (handle == null)");
        lines.Add(indent + "{");
        lines.Add(indent + "    throw new global::System.InvalidOperationException(NativeMethods.GetLastError() ?? \"BindingShim create call failed.\");");
        lines.Add(indent + "}");
        lines.Add("");
    }

    private static void EmitMethod(List<string> lines, string name, AbiFunction method)
    {
        var modifier = method.Static ? "static " : "";
        var declarations = ParameterDeclarations(method.Parameters);
        var stringIndex = FindStringParameter(method.Parameters);
        var stringName = stringIndex >= 0
            ? CSharpParameterName(method.Parameters[stringIndex], stringIndex)
            : null;
        var callArguments = new List<string>();
        if (!method.Static)
        {
            callArguments.Add("(void*)_handle");
        }

        callArguments.AddRange(BuildCallArgumentList(
            method.Parameters,
            stringIndex >= 0 ? "__hs_stringData" : null));
        if (method.NeedsPresenceFlag)
        {
            callArguments.Add("&__hs_hasValue");
        }

        var call = $"NativeMethods.TablePtr->{method.TableField}({string.Join(", ", callArguments)})";
        var returnType = method.ReturnKind switch
        {
            AbiKind.Void => "void",
            AbiKind.StringView => method.ReturnOptional ? "string?" : "string",
            AbiKind.Opaque => method.ReturnOwned && method.ReturnWrapperType is not null
                ? method.ReturnWrapperType + (method.ReturnNullable ? "?" : "")
                : method.ReturnOptional ? "nint?" : "nint",
            AbiKind.ArrayView => method.ArrayElementKind == AbiKind.StringView
                ? "string[]"
                : AbiPlan.CSharpType(method.ArrayElementKind) + "[]",
            AbiKind.Shared => $"global::Hosihikari.Bindings.{TypeNames.SurfaceNamespace(method.Surface)}.Interop.SharedHandle?",
            _ => AbiPlan.CSharpType(method.ReturnKind) + (method.ReturnOptional ? "?" : ""),
        };

        lines.Add($"    public {modifier}{returnType} {name}({declarations})");
        lines.Add("    {");
        if (method.NeedsPresenceFlag)
        {
            lines.Add("        var __hs_hasValue = false;");
        }

        EmitPinnedBody(
            lines,
            method.Parameters,
            stringIndex,
            stringName,
            FindVectorParameter(method.Parameters),
            "        ",
            bodyIndent => EmitMethodBody(lines, method, call, bodyIndent));
        lines.Add("    }");
    }

    private static void EmitMethodBody(List<string> lines, AbiFunction method, string call, string indent)
    {
        if (method.ReturnExpected)
        {
            if (method.ReturnKind == AbiKind.Void)
            {
                lines.Add(indent + $"{call};");
                lines.Add(indent + "if (!__hs_hasValue) { throw new global::System.InvalidOperationException(NativeMethods.GetLastError() ?? \"Binding API call returned an error.\"); }");
                return;
            }

            lines.Add(indent + $"var __hs_expectedResult = {call};");
            lines.Add(indent + "if (!__hs_hasValue) { throw new global::System.InvalidOperationException(NativeMethods.GetLastError() ?? \"Binding API call returned an error.\"); }");
            call = "__hs_expectedResult";
        }

        switch (method.ReturnKind)
        {
            case AbiKind.Void:
                lines.Add(indent + call + ";");
                break;
            case AbiKind.StringView:
                lines.Add(indent + $"var __hs_view = {call};");
                if (method.ReturnOptional)
                {
                    lines.Add(indent + "return __hs_hasValue"
                        + " ? global::System.Text.Encoding.UTF8.GetString(__hs_view.Data, checked((int)__hs_view.Size))"
                        + " : null;");
                }
                else
                {
                    lines.Add(indent + "return global::System.Text.Encoding.UTF8.GetString(__hs_view.Data, checked((int)__hs_view.Size));");
                }

                break;
            case AbiKind.ArrayView:
                lines.Add(indent + $"var __hs_view = {call};");
                if (method.ArrayElementKind == AbiKind.StringView)
                {
                    lines.Add(indent + "var __hs_items = (NativeMethods.StringView*)__hs_view.Data;");
                    lines.Add(indent + "var __hs_result = new string[checked((int)__hs_view.Size)];");
                    lines.Add(indent + "for (var __hs_i = 0; __hs_i < __hs_result.Length; __hs_i++)");
                    lines.Add(indent + "{");
                    lines.Add(indent + "    __hs_result[__hs_i] = global::System.Text.Encoding.UTF8.GetString(__hs_items[__hs_i].Data, checked((int)__hs_items[__hs_i].Size));");
                    lines.Add(indent + "}");
                    lines.Add(indent + "return __hs_result;");
                }
                else
                {
                    var elementType = AbiPlan.CSharpType(method.ArrayElementKind);
                    lines.Add(indent + $"var __hs_result = new {elementType}[checked((int)__hs_view.Size)];");
                    lines.Add(indent + "if (__hs_view.Size > 0)");
                    lines.Add(indent + "{");
                    lines.Add(indent + $"    new global::System.ReadOnlySpan<{elementType}>(__hs_view.Data, checked((int)__hs_view.Size)).CopyTo(__hs_result);");
                    lines.Add(indent + "}");
                    lines.Add(indent + "return __hs_result;");
                }

                break;
            case AbiKind.Shared:
                lines.Add(indent + $"var __hs_shared = {call};");
                lines.Add(indent + $"return __hs_shared.Holder == null ? null : new global::Hosihikari.Bindings.{TypeNames.SurfaceNamespace(method.Surface)}.Interop.SharedHandle((nint)__hs_shared.Holder, (nint)__hs_shared.Target, __hs_shared.Release);");
                break;
            case AbiKind.Opaque:
                if (method.ReturnOwned && method.ReturnWrapperType is not null)
                {
                    if (method.ReturnNullable)
                    {
                        lines.Add(indent + $"var __hs_handle = {call};");
                        var condition = method.ReturnOptional
                            ? "__hs_hasValue && __hs_handle != null"
                            : "__hs_handle != null";
                        lines.Add(indent + $"return {condition} ? new {method.ReturnWrapperType}((nint)__hs_handle) : null;");
                    }
                    else
                    {
                        lines.Add(indent + $"return new {method.ReturnWrapperType}((nint){call});");
                    }
                }
                else if (method.ReturnOptional)
                {
                    lines.Add(indent + $"var __hs_handle = {call};");
                    lines.Add(indent + "return __hs_hasValue ? (nint)__hs_handle : null;");
                }
                else
                {
                    lines.Add(indent + $"return (nint){call};");
                }

                break;
            default:
                if (method.ReturnOptional)
                {
                    lines.Add(indent + $"var __hs_value = {call};");
                    lines.Add(indent + $"return __hs_hasValue ? __hs_value : ({AbiPlan.CSharpType(method.ReturnKind)}?)null;");
                }
                else
                {
                    lines.Add(indent + $"return {call};");
                }

                break;
        }
    }

    private static void EmitMethodStub(
        List<string> lines,
        MemberRecord member,
        string name,
        string stubMessage)
    {
        var returnCanonical = member.Signature?.ReturnType ?? member.Type?.Canonical ?? "void";
        var returnType = TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = returnCanonical });
        var modifier = member.Static ? "static " : "";
        lines.Add($"    public {modifier}{returnType} {name}({CSharpParameters(member)}) =>");
        lines.Add($"        throw new global::System.NotSupportedException(\"{stubMessage}\");");
    }

    private static string ParameterDeclarations(IReadOnlyList<AbiParameter> parameters)
    {
        var declarations = new List<string>();
        for (var index = 0; index < parameters.Count; index++)
        {
            var parameter = parameters[index];
            if (parameter.Kind == AbiKind.Callback)
            {
                var (invoke, userData, release) = CallbackNames(parameter, index);
                declarations.Add($"nint {invoke}");
                declarations.Add($"nint {userData}");
                declarations.Add($"nint {release}");
                continue;
            }

            var type = parameter.IsVector
                ? parameter.VectorElementKind == AbiKind.StringView
                    ? "string[]"
                    : AbiPlan.CSharpType(parameter.VectorElementKind) + "[]"
                : parameter.IsOptional
                    ? parameter.Kind switch
                    {
                        AbiKind.StringView => "string?",
                        AbiKind.Opaque => (parameter.WrapperType ?? "nint") + "?",
                        _ => AbiPlan.CSharpType(parameter.Kind) + "?",
                    }
                    : AbiPlan.CSharpParameterType(parameter);
            declarations.Add($"{type} {CSharpParameterName(parameter, index)}");
        }

        return string.Join(", ", declarations);
    }

    private static (string Invoke, string UserData, string Release) CallbackNames(
        AbiParameter parameter,
        int index)
    {
        var name = CSharpParameterName(parameter, index);
        return (name + "Invoke", name + "UserData", name + "Release");
    }

    private static int FindStringParameter(IReadOnlyList<AbiParameter> parameters)
    {
        for (var index = 0; index < parameters.Count; index++)
        {
            if (parameters[index].Kind == AbiKind.StringView)
            {
                return index;
            }
        }

        return -1;
    }

    private static IEnumerable<string> BuildCallArgumentList(
        IReadOnlyList<AbiParameter> parameters,
        string? stringDataName)
    {
        var optionalPresence = new List<string>();
        for (var index = 0; index < parameters.Count; index++)
        {
            var parameter = parameters[index];
            var name = CSharpParameterName(parameter, index);
            if (parameter.IsOptional)
            {
                optionalPresence.Add(parameter.Kind switch
                {
                    AbiKind.StringView => $"{name} is not null",
                    AbiKind.Opaque => $"{name} is not null",
                    _ => $"{name}.HasValue",
                });
            }

            switch (parameter.Kind)
            {
                case AbiKind.StringView:
                    yield return stringDataName ?? name;
                    yield return "(nuint)__hs_stringBytes.Length";
                    break;
                case AbiKind.Opaque:
                    if (parameter.IsOptional)
                    {
                        yield return parameter.WrapperType is not null
                            ? $"(void*)({name}?.Handle ?? 0)"
                            : $"(void*)({name} ?? 0)";
                    }
                    else
                    {
                        yield return parameter.WrapperType is not null
                            ? $"(void*){name}.Handle"
                            : $"(void*){name}";
                    }

                    break;
                case AbiKind.Callback:
                {
                    var (invoke, userData, release) = CallbackNames(parameter, index);
                    yield return $"(void*){invoke}";
                    yield return $"(void*){userData}";
                    yield return $"(void*){release}";
                    break;
                }
                case AbiKind.Vector:
                    yield return "__hs_vectorData";
                    yield return parameter.VectorElementKind == AbiKind.StringView
                        ? "(nuint)__hs_vectorViews.Length"
                        : $"(nuint)({name}?.Length ?? 0)";
                    break;
                default:
                    yield return parameter.IsOptional
                        ? $"{name} ?? default({AbiPlan.CSharpType(parameter.Kind)})"
                        : name;
                    break;
            }
        }

        foreach (var presence in optionalPresence)
        {
            yield return presence;
        }
    }

    private static int FindVectorParameter(IReadOnlyList<AbiParameter> parameters)
    {
        for (var index = 0; index < parameters.Count; index++)
        {
            if (parameters[index].IsVector)
            {
                return index;
            }
        }

        return -1;
    }

    private static void EmitPinnedBody(
        List<string> lines,
        IReadOnlyList<AbiParameter> parameters,
        int stringIndex,
        string? stringName,
        int vectorIndex,
        string indent,
        Action<string> emitBody)
    {
        if (vectorIndex >= 0)
        {
            var vector = parameters[vectorIndex];
            var vectorName = CSharpParameterName(vector, vectorIndex);
            if (vector.VectorElementKind == AbiKind.StringView)
            {
                lines.Add(indent + $"var __hs_vectorItems = {vectorName} ?? global::System.Array.Empty<string>();");
                lines.Add(indent + "var __hs_vectorBytes = new byte[__hs_vectorItems.Length][];");
                lines.Add(indent + "var __hs_vectorViews = new NativeMethods.StringView[__hs_vectorItems.Length];");
                lines.Add(indent + "var __hs_vectorHandles = new nint[__hs_vectorItems.Length];");
                lines.Add(indent + "try");
                lines.Add(indent + "{");
                var inner = indent + "    ";
                lines.Add(inner + "for (var __hs_i = 0; __hs_i < __hs_vectorItems.Length; __hs_i++)");
                lines.Add(inner + "{");
                lines.Add(inner + "    __hs_vectorBytes[__hs_i] = global::System.Text.Encoding.UTF8.GetBytes(__hs_vectorItems[__hs_i] ?? string.Empty);");
                lines.Add(inner + "    var __hs_bytes = __hs_vectorBytes[__hs_i];");
                lines.Add(inner + "    var __hs_ptr = (nint)global::System.Runtime.InteropServices.Marshal.AllocHGlobal(__hs_bytes.Length == 0 ? 1 : __hs_bytes.Length);");
                lines.Add(inner + "    if (__hs_bytes.Length > 0) { global::System.Runtime.InteropServices.Marshal.Copy(__hs_bytes, 0, (nint)__hs_ptr, __hs_bytes.Length); }");
                lines.Add(inner + "    __hs_vectorHandles[__hs_i] = __hs_ptr;");
                lines.Add(inner + "    __hs_vectorViews[__hs_i] = new NativeMethods.StringView { Data = (byte*)__hs_ptr, Size = (nuint)__hs_bytes.Length };");
                lines.Add(inner + "}");
                lines.Add(inner + "fixed (NativeMethods.StringView* __hs_vectorData = __hs_vectorViews)");
                lines.Add(inner + "{");
                EmitStringAndBody(lines, parameters, stringIndex, stringName, inner + "    ", emitBody);
                lines.Add(inner + "}");
                lines.Add(indent + "}");
                lines.Add(indent + "finally");
                lines.Add(indent + "{");
                lines.Add(indent + "    for (var __hs_i = 0; __hs_i < __hs_vectorHandles.Length; __hs_i++) { if (__hs_vectorHandles[__hs_i] != 0) { global::System.Runtime.InteropServices.Marshal.FreeHGlobal((nint)__hs_vectorHandles[__hs_i]); } }");
                lines.Add(indent + "}");
                return;
            }

            var elementType = AbiPlan.CSharpType(vector.VectorElementKind);
            lines.Add(indent + $"fixed ({elementType}* __hs_vectorData = {vectorName})");
            lines.Add(indent + "{");
            EmitStringAndBody(lines, parameters, stringIndex, stringName, indent + "    ", emitBody);
            lines.Add(indent + "}");
            return;
        }

        EmitStringAndBody(lines, parameters, stringIndex, stringName, indent, emitBody);
    }

    private static void EmitStringAndBody(
        List<string> lines,
        IReadOnlyList<AbiParameter> parameters,
        int stringIndex,
        string? stringName,
        string indent,
        Action<string> emitBody)
    {
        if (stringIndex < 0)
        {
            emitBody(indent);
            return;
        }

        var expression = parameters[stringIndex].IsOptional
            ? $"{stringName} ?? string.Empty"
            : stringName!;
        lines.Add(indent + $"var __hs_stringBytes = global::System.Text.Encoding.UTF8.GetBytes({expression});");
        lines.Add(indent + "fixed (byte* __hs_stringData = __hs_stringBytes)");
        lines.Add(indent + "{");
        emitBody(indent + "    ");
        lines.Add(indent + "}");
    }

    private static string CSharpParameterName(AbiParameter parameter, int index)
    {
        return TypeNames.Sanitize(
            string.IsNullOrWhiteSpace(parameter.Name)
                ? "arg" + index.ToString(System.Globalization.CultureInfo.InvariantCulture)
                : parameter.Name);
    }

    private static void EmitDispose(List<string> lines, AbiFunction destroy)
    {
        lines.Add("    public void Dispose()");
        lines.Add("    {");
        lines.Add("        if (_handle != 0)");
        lines.Add("        {");
        lines.Add($"            NativeMethods.TablePtr->{destroy.TableField}((void*)_handle);");
        lines.Add("            _handle = 0;");
        lines.Add("        }");
        lines.Add("    }");
    }

    private static string CSharpParameters(MemberRecord member)
    {
        return member.Signature is null
            ? ""
            : string.Join(
                ", ",
                member.Signature.Parameters.Select((parameter, index) =>
                    $"{TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = parameter.Type })} {TypeNames.Sanitize(string.IsNullOrWhiteSpace(parameter.Name) ? $"arg{index}" : parameter.Name)}"));
    }
